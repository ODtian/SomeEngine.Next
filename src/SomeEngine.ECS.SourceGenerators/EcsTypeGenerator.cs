using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace SomeEngine.ECS.SourceGenerators;

[Generator]
public sealed class EcsTypeGenerator : IIncrementalGenerator
{
    private const string SchemaAttribute = "SomeEngine.ECS.Relations.RelationSchemaAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var types = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is StructDeclarationSyntax or RecordDeclarationSyntax or
                    GenericNameSyntax or InvocationExpressionSyntax,
                static (syntax, _) => GetTypes(syntax))
            .Collect().Combine(context.CompilationProvider);
        context.RegisterSourceOutput(types, static (output, input) => Generate(output, input.Left, input.Right));
    }

    private static ImmutableArray<INamedTypeSymbol> GetTypes(GeneratorSyntaxContext context)
    {
        ISymbol? symbol = context.Node is StructDeclarationSyntax or RecordDeclarationSyntax
            ? context.SemanticModel.GetDeclaredSymbol(context.Node)
            : context.SemanticModel.GetSymbolInfo(context.Node).Symbol;
        return symbol switch
        {
            INamedTypeSymbol type => ImmutableArray.Create(type),
            IMethodSymbol method => method.TypeArguments.OfType<INamedTypeSymbol>().ToImmutableArray(),
            _ => ImmutableArray<INamedTypeSymbol>.Empty,
        };
    }

    private static void Generate(SourceProductionContext context,
        ImmutableArray<ImmutableArray<INamedTypeSymbol>> inputs, Compilation compilation)
    {
        var generatedTypes = compilation.GetTypeByMetadataName("SomeEngine.ECS.Registry.GeneratedEcsTypes");
        if (generatedTypes is null)
            return;
        var types = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        var fallbackTypes = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        foreach (var input in inputs)
            foreach (var type in input)
            {
                AddType(type, types);
                AddFallbackType(type, fallbackTypes);
            }
        foreach (var type in types.ToArray())
        {
            var schema = type.GetAttributes().FirstOrDefault(IsSchema);
            if (schema is null)
                continue;
            bool directed = Convert.ToInt32(schema.ConstructorArguments[0].Value) == 0;
            var endpoint = compilation.GetTypeByMetadataName(directed
                ? "SomeEngine.ECS.Relations.DirectedRelationEndpoints`1"
                : "SomeEngine.ECS.Relations.UndirectedRelationEndpoints`1");
            if (endpoint is not null)
                types.Add(endpoint.Construct(type));
        }
        if (types.Count == 0 && fallbackTypes.Count == 0)
            return;
        var storage = new JobStorageTypeAnalysis(compilation);
        var closedInaccessibleTypes = fallbackTypes.OrderBy(FullName, StringComparer.Ordinal).ToArray();
        var fieldRoots = new HashSet<(string Assembly, string Name)>();
        var visited = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        foreach (var type in fallbackTypes)
            AddFieldRoots(type, storage, visited, fieldRoots);
        var text = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace SomeEngine.ECS.Generated;\n\ninternal static class EcsTypeRegistration\n{\n");
        foreach (var root in fieldRoots.OrderBy(static root => root.Assembly, StringComparer.Ordinal)
                     .ThenBy(static root => root.Name, StringComparer.Ordinal))
            text.Append("    [global::System.Diagnostics.CodeAnalysis.DynamicDependency(")
                .Append("global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.PublicFields | ")
                .Append("global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.NonPublicFields, ")
                .Append(Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(root.Name, quote: true)).Append(", ")
                .Append(Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(root.Assembly, quote: true)).AppendLine(")]");
        text.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]")
            .AppendLine("    internal static void RegisterTypes()\n    {");
        foreach (var type in types.OrderBy(FullName, StringComparer.Ordinal))
        {
            string name = FullName(type);
            text.Append("        global::SomeEngine.ECS.Registry.GeneratedEcsTypes.RegisterJobStorage<")
                .Append(name).Append(">(").Append(storage.IsAliasFree(type) ? "true" : "false").AppendLine(");");
            var schema = type.GetAttributes().FirstOrDefault(IsSchema);
            if (schema is null)
                continue;
            int direction = Convert.ToInt32(schema.ConstructorArguments[0].Value);
            int cardinality = schema.ConstructorArguments.Length > 1 ? Convert.ToInt32(schema.ConstructorArguments[1].Value) : 0;
            bool selfEdge = !schema.NamedArguments.Any(argument => argument.Key == "AllowSelfEdge" && argument.Value.Value is false);
            text.Append("        global::SomeEngine.ECS.Registry.GeneratedEcsTypes.RegisterRelationSchema<")
                .Append(name).Append(">(new global::SomeEngine.ECS.Relations.RelationSchema((global::SomeEngine.ECS.Relations.RelationDirection)")
                .Append(direction).Append(", (global::SomeEngine.ECS.Relations.RelationCardinality)")
                .Append(cardinality).Append(", ").Append(selfEdge ? "true" : "false").AppendLine("));");
        }
        if (closedInaccessibleTypes.Length != 0)
        {
            text.AppendLine("        if (!global::System.Runtime.CompilerServices.RuntimeFeature.IsDynamicCodeSupported)")
                .AppendLine("        {");
            for (int i = 0; i < closedInaccessibleTypes.Length; i++)
            {
                text.Append("            global::System.Threading.Volatile.Write(ref AliasFree")
                    .Append(i).Append("(null), ")
                    .Append(storage.IsAliasFree(closedInaccessibleTypes[i]) ? "1" : "-1").AppendLine(");");
            }
            text.AppendLine("        }");
        }
        text.AppendLine("    }");

        // Inaccessible storage uses the same closed generic cache as RegisterJobStorage<T>.
        // A field accessor avoids requiring a generated C# reference to the private value type.
        for (int i = 0; i < closedInaccessibleTypes.Length; i++)
        {
            string cacheType = "SomeEngine.ECS.Registry.JobStorageTypeMetadata`1[[" +
                AssemblyQualifiedTypeName(closedInaccessibleTypes[i], compilation) + "]], " +
                generatedTypes.ContainingAssembly.Identity.Name;
            text.AppendLine()
                .AppendLine("    [global::System.Runtime.CompilerServices.UnsafeAccessor(")
                .AppendLine("        global::System.Runtime.CompilerServices.UnsafeAccessorKind.StaticField, Name = \"s_aliasFree\")]")
                .Append("    private static extern ref int AliasFree").Append(i).AppendLine("(")
                .Append("        [global::System.Runtime.CompilerServices.UnsafeAccessorType(")
                .Append(Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(cacheType, quote: true))
                .AppendLine(")] object? declaringType);");
        }
        text.AppendLine("}");
        context.AddSource("EcsTypeRegistration.g.cs", text.ToString());
    }

    private static void AddType(INamedTypeSymbol type, HashSet<INamedTypeSymbol> types)
    {
        if (!Accessible(type) || ContainsTypeParameter(type))
            return;
        if (type.IsValueType && !type.IsRefLikeType && type.AllInterfaces.Any(IsStorage))
            types.Add(type);
        foreach (var argument in type.TypeArguments.OfType<INamedTypeSymbol>())
            AddType(argument, types);
    }

    private static void AddFallbackType(INamedTypeSymbol type, HashSet<INamedTypeSymbol> types)
    {
        if (ContainsTypeParameter(type))
            return;
        if (!Accessible(type) && type.IsValueType && !type.IsRefLikeType && type.AllInterfaces.Any(IsStorage))
            types.Add(type);
        foreach (var argument in type.TypeArguments.OfType<INamedTypeSymbol>())
            AddFallbackType(argument, types);
    }

    // The runtime fallback inspects private backing fields recursively. A field root is emitted
    // by documentation type name (not reflection nesting syntax), so private types need no partial declaration.
    private static void AddFieldRoots(INamedTypeSymbol type, JobStorageTypeAnalysis storage,
        HashSet<INamedTypeSymbol> visited, HashSet<(string Assembly, string Name)> roots)
    {
        if (!type.IsValueType || type.IsRefLikeType || type.TypeKind == TypeKind.Enum ||
            type.SpecialType is SpecialType.System_Boolean or SpecialType.System_Byte or SpecialType.System_SByte or
                SpecialType.System_Char or SpecialType.System_Int16 or SpecialType.System_UInt16 or
                SpecialType.System_Int32 or SpecialType.System_UInt32 or SpecialType.System_Int64 or
                SpecialType.System_UInt64 or SpecialType.System_Single or SpecialType.System_Double or
                SpecialType.System_IntPtr or SpecialType.System_UIntPtr)
            return;
        type = storage.WithAllFields(type);
        if (!visited.Add(type))
            return;
        var definition = type.OriginalDefinition;
        roots.Add((definition.ContainingAssembly.Identity.Name, DocumentationTypeName(definition)));
        foreach (var field in type.GetMembers().OfType<IFieldSymbol>())
        {
            if (field.IsStatic || field.IsConst) continue;
            if (field.Type is INamedTypeSymbol nested)
                AddFieldRoots(nested, storage, visited, roots);
        }
    }

    private static string DocumentationTypeName(INamedTypeSymbol type)
    {
        string? id = DocumentationCommentId.CreateDeclarationId(type);
        if (id is null || !id.StartsWith("T:", StringComparison.Ordinal))
            throw new InvalidOperationException("A documentation type identifier is required for storage field metadata.");
        return id.Substring(2);
    }

    private static string AssemblyQualifiedTypeName(ITypeSymbol type, Compilation compilation)
    {
        if (type is IDynamicTypeSymbol)
            type = compilation.GetSpecialType(SpecialType.System_Object);
        ITypeSymbol element = type;
        while (element is IArrayTypeSymbol array)
            element = array.ElementType;
        if (element is IDynamicTypeSymbol)
            element = compilation.GetSpecialType(SpecialType.System_Object);
        return MetadataTypeName(type, compilation) + ", " + element.ContainingAssembly.Identity.Name;
    }

    private static string MetadataTypeName(ITypeSymbol type, Compilation compilation)
    {
        if (type is IDynamicTypeSymbol)
            type = compilation.GetSpecialType(SpecialType.System_Object);
        if (type is IArrayTypeSymbol array)
        {
            string dimensions = array.IsSZArray ? "[]" :
                array.Rank == 1 ? "[*]" : "[" + new string(',', array.Rank - 1) + "]";
            return MetadataTypeName(array.ElementType, compilation) + dimensions;
        }

        var hierarchy = new Stack<INamedTypeSymbol>();
        for (INamedTypeSymbol? current = (INamedTypeSymbol)type; current is not null; current = current.ContainingType)
            hierarchy.Push(current);
        var namespaces = new Stack<string>();
        for (INamespaceSymbol? current = type.ContainingNamespace;
             current is not null && !current.IsGlobalNamespace; current = current.ContainingNamespace)
            namespaces.Push(current.MetadataName);

        string name = (namespaces.Count == 0 ? "" : string.Join(".", namespaces) + ".") +
            string.Join("+", hierarchy.Select(static current => current.MetadataName));
        var arguments = hierarchy.SelectMany(static current => current.TypeArguments).ToArray();
        if (arguments.Length != 0)
            name += "[[" + string.Join("],[", arguments.Select(argument =>
                AssemblyQualifiedTypeName(argument, compilation))) + "]]";
        return name;
    }

    private static bool Accessible(ITypeSymbol type) => type switch
    {
        INamedTypeSymbol named => named.DeclaredAccessibility is Accessibility.Public or Accessibility.Internal &&
            (named.ContainingType is null || Accessible(named.ContainingType)) && named.TypeArguments.All(Accessible),
        IArrayTypeSymbol array => Accessible(array.ElementType),
        _ => true,
    };

    private static bool ContainsTypeParameter(ITypeSymbol type) => type is ITypeParameterSymbol ||
        type is IArrayTypeSymbol array && ContainsTypeParameter(array.ElementType) ||
        type is INamedTypeSymbol named && (named.TypeArguments.Any(ContainsTypeParameter) ||
            named.ContainingType is not null && ContainsTypeParameter(named.ContainingType));

    private static bool IsSchema(AttributeData attribute) => attribute.AttributeClass?.ToDisplayString() == SchemaAttribute;

    private static bool IsStorage(INamedTypeSymbol type) => type.ToDisplayString() is
        "SomeEngine.ECS.IComponent" or "SomeEngine.ECS.Components.ITag" or
        "SomeEngine.ECS.Components.ISparseComponent" or "SomeEngine.ECS.Components.IBufferElement" or
        "SomeEngine.ECS.Components.ISharedComponent";

    private static string FullName(INamedTypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
}
