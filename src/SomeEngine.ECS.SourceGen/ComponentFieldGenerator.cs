using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace SomeEngine.ECS.SourceGen;

[Generator]
public sealed class ComponentFieldGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var declarations = context.SyntaxProvider.ForAttributeWithMetadataName(
            "SomeEngine.ECS.GenerateFieldsAttribute",
            static (node, _) => node is StructDeclarationSyntax,
            static (data, _) => (INamedTypeSymbol)data.TargetSymbol);
        context.RegisterSourceOutput(declarations.Combine(context.CompilationProvider),
            static (output, data) => Generate(output, data.Left, data.Right));
    }

    private static void Generate(SourceProductionContext output, INamedTypeSymbol root, Compilation compilation)
    {
        var fields = new List<Field>();
        foreach (ISymbol member in root.GetMembers())
        {
            if (member.IsStatic || member.DeclaredAccessibility != Accessibility.Public)
                continue;
            ITypeSymbol? type = member switch
            {
                IFieldSymbol { IsReadOnly: false } field => field.Type,
                IPropertySymbol { GetMethod: not null, SetMethod: { DeclaredAccessibility: Accessibility.Public }, IsIndexer: false } property => property.Type,
                _ => null,
            };
            if (type?.IsUnmanagedType == true)
                fields.Add(new Field(member.Name, type, new[] { member }, null));
        }
        foreach (AttributeData attribute in root.GetAttributes())
        {
            if (attribute.AttributeClass?.ToDisplayString() != "SomeEngine.ECS.ComponentFieldAttribute")
                continue;
            string? name = attribute.NamedArguments.FirstOrDefault(pair => pair.Key == "Name").Value.Value as string;
            if (attribute.ConstructorArguments[0].Value is string path)
            {
                var members = new List<ISymbol>();
                ITypeSymbol type = root;
                foreach (string part in path.Split('.'))
                {
                    ISymbol member = type.GetMembers(part).First();
                    members.Add(member);
                    type = MemberType(member);
                }
                name ??= path.Replace(".", "");
                fields.RemoveAll(field => field.Name == name);
                fields.Add(new Field(name, type, members.ToArray(), null));
            }
            else if (attribute.ConstructorArguments[0].Value is INamedTypeSymbol access)
            {
                INamedTypeSymbol fieldInterface = access.AllInterfaces.First(type =>
                    type.OriginalDefinition.ToDisplayString() == "SomeEngine.ECS.IFieldAccess<TComponent, TValue>");
                name ??= (string)attribute.ConstructorArguments[1].Value!;
                fields.Add(new Field(name, fieldInterface.TypeArguments[1], Array.Empty<ISymbol>(), access));
            }
        }

        string rootName = TypeName(root);
        string prefix = root.Name;
        for (INamedTypeSymbol? container = root.ContainingType; container is not null; container = container.ContainingType)
            prefix = container.Name + "_" + prefix;
        string visibility = root.DeclaredAccessibility == Accessibility.Public ? "public" : "internal";
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        if (!root.ContainingNamespace.IsGlobalNamespace)
            source.Append("namespace ").Append(root.ContainingNamespace.ToDisplayString()).AppendLine(";");
        source.Append(visibility).Append(" enum ").Append(prefix).AppendLine("Fields : ushort\n{");
        for (int index = 0; index < fields.Count; index++)
            source.Append("    ").Append(Escape(fields[index].Name)).Append(" = ").Append(index + 1).AppendLine(",");
        source.AppendLine("}");
        source.Append(visibility).Append(" static class ").Append(prefix).AppendLine("FieldAccess\n{");
        foreach (Field field in fields.Where(field => field.Access is null))
        {
            string valueType = TypeName(field.Type);
            bool offset = HasOffset(field);
            source.Append("    public readonly struct ").Append(Escape(field.Name))
                .Append(" : global::SomeEngine.ECS.IFieldAccess<").Append(rootName).Append(", ").Append(valueType).AppendLine(">\n    {");
            if (offset)
            {
                source.AppendLine("        public static readonly ushort Offset = GetOffset();");
                source.AppendLine("        private static ushort GetOffset()\n        {");
                source.Append("            ").Append(rootName).AppendLine(" component = default;");
                source.Append("            return (ushort)global::System.Runtime.CompilerServices.Unsafe.ByteOffset(ref global::System.Runtime.CompilerServices.Unsafe.As<")
                    .Append(rootName).Append(", byte>(ref component), ref global::System.Runtime.CompilerServices.Unsafe.As<").Append(valueType).Append(", byte>(ref component.")
                    .Append(string.Join(".", field.Members.Select(member => Escape(member.Name)))).AppendLine("));\n        }");
                source.Append("        public static ").Append(valueType).Append(" Read(in ").Append(rootName).Append(" component) => global::System.Runtime.CompilerServices.Unsafe.ReadUnaligned<")
                    .Append(valueType).Append(">(ref global::System.Runtime.CompilerServices.Unsafe.Add(ref global::System.Runtime.CompilerServices.Unsafe.As<").Append(rootName)
                    .AppendLine(", byte>(ref global::System.Runtime.CompilerServices.Unsafe.AsRef(in component)), Offset));");
                source.Append("        public static void Write(ref ").Append(rootName).Append(" component, in ").Append(valueType)
                    .Append(" value) => global::System.Runtime.CompilerServices.Unsafe.WriteUnaligned(ref global::System.Runtime.CompilerServices.Unsafe.Add(ref global::System.Runtime.CompilerServices.Unsafe.As<")
                    .Append(rootName).AppendLine(", byte>(ref component), Offset), value);\n    }");
                continue;
            }
            source.Append("        public static ").Append(valueType).Append(" Read(in ").Append(rootName)
                .Append(" component) => component.").Append(string.Join(".", field.Members.Select(member => Escape(member.Name)))).AppendLine(";");
            source.Append("        public static void Write(ref ").Append(rootName).Append(" component, in ")
                .Append(valueType).AppendLine(" value)\n        {");
            string parent = "component";
            for (int index = 0; index < field.Members.Length - 1; index++)
            {
                source.Append("            var part").Append(index).Append(" = ").Append(parent).Append('.').Append(Escape(field.Members[index].Name)).AppendLine(";");
                parent = "part" + index;
            }
            source.Append("            ").Append(parent).Append('.').Append(Escape(field.Members.Last().Name)).AppendLine(" = value;");
            for (int index = field.Members.Length - 2; index >= 0; index--)
                if (MemberType(field.Members[index]).IsValueType)
                    source.Append("            ").Append(index == 0 ? "component" : "part" + (index - 1)).Append('.').Append(Escape(field.Members[index].Name))
                        .Append(" = part").Append(index).AppendLine(";");
            source.AppendLine("        }\n    }");
        }
        source.AppendLine("}");
        if (compilation.GetTypeByMetadataName("SomeEngine.Animation.Channel`1") is not null)
        {
            source.Append(visibility).Append(" static class ").Append(prefix).AppendLine("Channels\n{");
            foreach (Field field in fields)
            {
                string access = field.Access is null ? prefix + "FieldAccess." + Escape(field.Name) : TypeName(field.Access);
                source.Append("    public static readonly global::SomeEngine.Animation.Channel<").Append(TypeName(field.Type)).Append("> ")
                    .Append(Escape(field.Name)).Append(" = global::SomeEngine.Animation.Channel<").Append(TypeName(field.Type)).Append(">.Of<")
                    .Append(rootName).Append(", ").Append(access).Append(">((ushort)").Append(prefix).Append("Fields.").Append(Escape(field.Name))
                    .Append(", throughReference: ").Append(field.Access is not null || field.Members.Take(field.Members.Length - 1).Any(member => MemberType(member).IsReferenceType) ? "true" : "false");
                if (HasOffset(field))
                    source.Append(", offset: ").Append(access).Append(".Offset");
                source.AppendLine(");");
            }
            source.AppendLine("}");
            if (compilation.GetTypeByMetadataName("SomeEngine.Views.Scope") is not null)
            {
                source.Append(visibility).Append(" static class ").Append(prefix).AppendLine("FieldTargets\n{");
                foreach (Field field in fields)
                    source.Append("    public static global::SomeEngine.ECS.Entities.Entity Set").Append(field.Name)
                        .Append("(this global::SomeEngine.ECS.Entities.Entity node, ").Append(TypeName(field.Type)).AppendLine(" value)\n    {")
                        .Append("        global::SomeEngine.Views.Scope.Set(node, ").Append(prefix).Append("Channels.").Append(Escape(field.Name)).AppendLine(", value);\n        return node;\n    }");
                source.AppendLine("}");
            }
        }
        output.AddSource(prefix + ".Fields.g.cs", source.ToString());
    }

    private static ITypeSymbol MemberType(ISymbol member) => member is IFieldSymbol field ? field.Type : ((IPropertySymbol)member).Type;
    private static bool HasOffset(Field field) => field.Access is null && field.Members.All(member => member is IFieldSymbol) &&
        field.Members.Take(field.Members.Length - 1).All(member => MemberType(member).IsValueType);
    private static string TypeName(ITypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
    private static string Escape(string name) => SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;

    private sealed class Field(string name, ITypeSymbol type, ISymbol[] members, INamedTypeSymbol? access)
    {
        public string Name { get; } = name;
        public ITypeSymbol Type { get; } = type;
        public ISymbol[] Members { get; } = members;
        public INamedTypeSymbol? Access { get; } = access;
    }
}
