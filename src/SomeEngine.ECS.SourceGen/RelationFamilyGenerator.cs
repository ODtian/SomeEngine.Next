using System.Text;
using Microsoft.CodeAnalysis;

namespace SomeEngine.ECS.SourceGen;

[Generator]
public sealed class RelationFamilyGenerator : IIncrementalGenerator
{
    private static readonly string[] Positions =
        ["first", "second", "third", "fourth", "fifth", "sixth", "seventh", "eighth"];

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var enabled = context.AnalyzerConfigOptionsProvider.Select(static (options, _) =>
            options.GlobalOptions.TryGetValue("build_property.SomeEngineGenerateRelationFamilies", out string? value) &&
            value == "true");
        context.RegisterSourceOutput(enabled, static (output, generate) =>
        {
            if (!generate)
                return;
            for (int arity = 1; arity <= 8; arity++)
                output.AddSource($"RelationFamily{arity}.g.cs", GenerateFamily(arity));
            output.AddSource("RelationQueryViews.g.cs", GenerateViews());
        });
    }

    private static string GenerateFamily(int arity)
    {
        var text = new StringBuilder(
            "// <auto-generated/>\n#nullable enable\nusing SomeEngine.ECS.Entities;\nusing SomeEngine.ECS.Queries;\nusing System.Runtime.CompilerServices;\nnamespace SomeEngine.ECS.Relations;\n\n");
        string components = string.Join(", ", Enumerable.Range(1, arity).Select(i => $"T{i}"));
        string row = arity == 1 ? "Entity" : $"({string.Join(", ", Enumerable.Repeat("Entity", arity))})";
        AppendInterface(text, arity, components);
        AppendBinding(text, arity, components, row);
        AppendFilter(text, arity, components, row, "Where");
        AppendFilter(text, arity, components, row, "Except");
        AppendProduct(text, arity, row);
        return text.ToString();
    }

    private static void AppendInterface(StringBuilder text, int arity, string components)
    {
        string arguments = string.Join(", ", Enumerable.Range(0, arity).Select(i => $"in T{i + 1} {Positions[i]}"));
        text.AppendLine($"public interface IRelation<{components}>")
            .AppendLine("{");
        if (arity == 2)
            text.AppendLine("    /// <summary>Declares that exchanging two components of the same type preserves Matches.</summary>")
                .AppendLine("    static virtual bool IsSymmetric => false;\n");
        text.AppendLine($"    bool Matches({arguments});");
        text.AppendLine("}\n");
    }

    private static void AppendComponentConstraints(StringBuilder text, int arity)
    {
        for (int i = 1; i <= arity; i++)
            text.AppendLine($"    where T{i} : struct");
    }

    private static void AppendBinding(StringBuilder text, int arity, string components, string row)
    {
        string rowParameter = arity == 1 ? "entity" : arity == 2 ? "pair" : "row";
        text.AppendLine($"public ref struct ComponentRelation<TRelation, {components}> : IQueryRelation<{row}>")
            .AppendLine($"    where TRelation : struct, IRelation<{components}>, allows ref struct");
        AppendComponentConstraints(text, arity);
        text.AppendLine("{");
        text
            .AppendLine("    private readonly QueryCursor _query;")
            .AppendLine("    private TRelation _relation;\n")
            .AppendLine("    public ComponentRelation(QueryCursor query, TRelation relation)")
            .AppendLine("    {")
            .AppendLine("        _query = query;")
            .AppendLine("        _relation = relation;")
            .AppendLine("    }\n")
            .AppendLine($"    public bool Matches(in {row} {rowParameter})")
            .AppendLine("    {")
            .Append("        if (");
        for (int i = 0; i < arity; i++)
        {
            string entity = arity == 1 ? rowParameter : $"{rowParameter}.Item{i + 1}";
            if (i > 0) text.Append(" ||\n            ");
            text.Append($"!_query.TryGetRow({entity}, out var {Positions[i]})");
        }
        string rowArguments = string.Join(", ", Positions.Take(arity).Select(name => $"in {name}"));
        string rowParameters = string.Join(", ", Positions.Take(arity).Select(name => $"scoped in QueryRow {name}"));
        string arguments = string.Join(", ", Enumerable.Range(0, arity).Select(i =>
            $"in {Positions[i]}Component.Value"));
        text.AppendLine(")")
            .AppendLine("            return false;")
            .AppendLine($"        return Matches({rowArguments});")
            .AppendLine("    }\n")
            .AppendLine("    [MethodImpl(MethodImplOptions.AggressiveInlining)]")
            .AppendLine($"    public bool Matches({rowParameters})")
            .AppendLine("    {")
            .Append("        if (");
        for (int i = 0; i < arity; i++)
        {
            if (i > 0) text.Append(" || ");
            text.Append($"!{Positions[i]}.TryReadRef<T{i + 1}>(out var {Positions[i]}Component)");
        }
        text.AppendLine(")")
            .AppendLine("            return false;")
            .AppendLine($"        return _relation.Matches({arguments});")
            .AppendLine("    }");
        if (arity == 2)
            text.AppendLine("    [MethodImpl(MethodImplOptions.AggressiveInlining)]")
                .AppendLine($"    public bool Matches(in {row} pair, scoped in QueryRow first, scoped in QueryRow second) =>")
                .AppendLine("        Matches(in first, in second);");
        else
            text.AppendLine($"    public bool Matches(in {row} value, scoped in QueryRow firstRow, scoped in QueryRow secondRow) => Matches(in value);");
        text.AppendLine("}\n");
    }

    private static void AppendFilter(StringBuilder text, int arity, string components, string row, string operation)
    {
        string binding = $"ComponentRelation<TRelation, {components}>";
        string predicate = binding;
        text.AppendLine($"public readonly struct Component{operation}<TEnumerable, TRelation, {components}> : IQueryRelationEnumerable<{row}>")
            .AppendLine($"    where TEnumerable : struct, IQueryRelationEnumerable<{row}>")
            .AppendLine($"    where TRelation : struct, IRelation<{components}>");
        AppendComponentConstraints(text, arity);
        text.AppendLine("{")
            .AppendLine("    private readonly TEnumerable _enumerable;")
            .AppendLine("    private readonly TRelation _relation;\n")
            .AppendLine($"    public Component{operation}(TEnumerable enumerable, TRelation relation)")
            .AppendLine("    {")
            .AppendLine("        _enumerable = enumerable;")
            .AppendLine("        _relation = relation;")
            .AppendLine("    }\n")
            .AppendLine("    public World World => _enumerable.World;\n")
            .AppendLine("    public int QueryCount => _enumerable.QueryCount;\n")
            .AppendLine("    public static bool ReadsFromSingleQuery => TEnumerable.ReadsFromSingleQuery;\n")
            .AppendLine("    public QueryHandle GetQuery(int position) => _enumerable.GetQuery(position);\n")
            .AppendLine("    public QueryDefinition AddReads(QueryDefinition definition, int position)")
            .AppendLine("    {")
            .AppendLine("        definition = _enumerable.AddReads(definition, position);");
        for (int i = 0; i < arity; i++)
            text.AppendLine($"        if (position == {i} || QueryCount <= 1)")
                .AppendLine($"            definition = definition.WithOptionalRead<T{i + 1}>();");
        text.AppendLine("        return definition;")
            .AppendLine("    }\n")
            .AppendLine("    public bool Enumerate<TOutput>(RelationQueryViews queries, ref TOutput output)")
            .AppendLine($"        where TOutput : struct, IQueryRelationOutput<{row}>, allows ref struct")
            .AppendLine("    {");
        text.AppendLine($"        var relation = new {binding}(queries.Access, _relation);");
        text.AppendLine($"        var filtered = new RelationFilterOutput<{predicate}, TOutput, {row}, {operation}Selection>(relation, output);")
            .AppendLine("        try")
            .AppendLine("        {")
            .AppendLine("            return _enumerable.Enumerate(queries, ref filtered);")
            .AppendLine("        }")
            .AppendLine("        finally")
            .AppendLine("        {")
            .AppendLine("            output = filtered.Output;")
            .AppendLine("        }")
            .AppendLine("    }")
            .AppendLine("}\n");
    }

    private static void AppendProduct(StringBuilder text, int arity, string row)
    {
        string name = arity == 1 ? "EntityProduct" : $"EntityProduct{arity}";
        var names = arity == 1 ? new[] { "members" } : Positions.Take(arity).ToArray();
        string arguments = string.Join(", ", names);
        string parameters = string.Join(", ", names.Select(name => $"QueryHandle {name}"));
        text.AppendLine("public static partial class RelationQueries")
            .AppendLine("{")
            .AppendLine($"    public static RelationQuery<{name}, {row}> Product(this World world, {parameters}) =>")
            .AppendLine($"        new(new {name}(world, {arguments}));")
            .AppendLine("}\n")
            .AppendLine($"public readonly struct {name} : IQueryRelationEnumerable<{row}>")
            .AppendLine("{");
        foreach (string item in names)
            text.AppendLine($"    private readonly QueryHandle _{item};");
        text.AppendLine()
            .AppendLine($"    public {name}(World world, {parameters})")
            .AppendLine("    {")
            .AppendLine("        World = world;");
        foreach (string item in names)
            text.AppendLine($"        _{item} = {item};");
        text.AppendLine("    }\n")
            .AppendLine("    public World World { get; }\n")
            .AppendLine($"    public int QueryCount => {arity};\n");
        if (arity == 1)
            text.AppendLine("    public static bool ReadsFromSingleQuery => true;\n");
        if (arity == 1)
            text.AppendLine("    public QueryHandle GetQuery(int position) => _members;\n");
        else
        {
            text.AppendLine("    public QueryHandle GetQuery(int position) => position switch")
                .AppendLine("    {");
            for (int i = 0; i < arity - 1; i++)
                text.AppendLine($"        {i} => _{names[i]},");
            text.AppendLine($"        _ => _{names[arity - 1]},")
                .AppendLine("    };\n");
        }
        text.AppendLine("    public QueryDefinition AddReads(QueryDefinition definition, int position) => definition;\n")
            .AppendLine("    public bool Enumerate<TOutput>(RelationQueryViews queries, ref TOutput output)")
            .AppendLine($"        where TOutput : struct, IQueryRelationOutput<{row}>, allows ref struct")
            .AppendLine("    {");
        for (int i = 0; i < arity; i++)
        {
            string indent = new(' ', 8 + 4 * i);
            string view = char.ToUpperInvariant(Positions[i][0]) + Positions[i].Substring(1);
            text.AppendLine($"{indent}foreach (var {Positions[i]} in queries.{view}.Rows)")
                .AppendLine($"{indent}{{");
        }
        string bodyIndent = new(' ', 8 + 4 * arity);
        string values = string.Join(", ", Positions.Take(arity).Select(name => $"{name}.Entity"));
        string value = arity == 1 ? "first.Entity" : $"({values})";
        text.AppendLine($"{bodyIndent}{(arity == 1 ? "Entity" : "var")} row = {value};")
            .AppendLine($"{bodyIndent}if (!output.Add(in row))")
            .AppendLine($"{bodyIndent}    return false;");
        for (int i = arity - 1; i >= 0; i--)
            text.AppendLine(new string(' ', 8 + 4 * i) + "}");
        text.AppendLine("        return true;")
            .AppendLine("    }")
            .AppendLine("}\n");
    }

    private static string GenerateViews()
    {
        string[] names = Positions.Select(name => char.ToUpperInvariant(name[0]) + name.Substring(1)).ToArray();
        string parameters = string.Join(", ", Positions.Select(name => $"QueryCursor {name}"));
        var text = new StringBuilder(
            "// <auto-generated/>\n#nullable enable\nusing SomeEngine.ECS.Queries;\nnamespace SomeEngine.ECS.Relations;\n\n");
        text.AppendLine("public readonly ref struct RelationQueryViews")
            .AppendLine("{")
            .AppendLine("    public RelationQueryViews(QueryCursor first)")
            .AppendLine("        : this(first, first, default, default, default, default, default, default, default) { }\n")
            .AppendLine("    public RelationQueryViews(QueryCursor access, QueryCursor first, QueryCursor second)")
            .AppendLine("        : this(access, first, second, default, default, default, default, default, default) { }\n")
            .AppendLine($"    public RelationQueryViews(QueryCursor access, {parameters})")
            .AppendLine("    {")
            .AppendLine("        Access = access;");
        for (int i = 0; i < 8; i++)
            text.AppendLine($"        {names[i]} = {Positions[i]};");
        text.AppendLine("    }\n")
            .AppendLine("    public QueryCursor Access { get; }\n");
        foreach (string name in names)
            text.AppendLine($"    public QueryCursor {name} {{ get; }}\n");
        text.AppendLine("    internal RelationQueryViews WithQuery(int position, QueryCursor query) =>")
            .AppendLine("        new(Access,");
        for (int i = 0; i < 8; i++)
            text.AppendLine($"            position == {i} ? query : {names[i]}{(i == 7 ? ");" : ",")}");
        text.AppendLine("}");
        return text.ToString();
    }
}
