using System.Text;
using Microsoft.CodeAnalysis;

namespace SomeEngine.ECS.SourceGen;

[Generator]
public sealed class RelationFamilyGenerator : IIncrementalGenerator
{
    private static readonly string[] Positions = ["first", "second", "third", "fourth", "fifth", "sixth", "seventh", "eighth"];

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var enabled = context.AnalyzerConfigOptionsProvider.Select(static (options, _) =>
            options.GlobalOptions.TryGetValue("build_property.SomeEngineGenerateRelationFamilies", out string? value) && value == "true");
        context.RegisterSourceOutput(enabled, static (output, generate) =>
        {
            if (!generate) return;
            for (int arity = 1; arity <= 8; arity++) output.AddSource($"RelationFamily{arity}.g.cs", GenerateFamily(arity));
            output.AddSource("RelationQueryViews.g.cs", GenerateViews());
        });
    }

    private static string GenerateFamily(int arity)
    {
        var text = new StringBuilder("// <auto-generated/>\n#nullable enable\nusing System;\nusing SomeEngine.ECS.Entities;\nnamespace SomeEngine.ECS.Relations;\n");
        string components = string.Join(", ", Enumerable.Range(1, arity).Select(index => $"T{index}"));
        string row = arity == 1 ? "Entity" : $"({string.Join(", ", Enumerable.Repeat("Entity", arity))})";
        text.AppendLine($"public interface IRelation<{components}>\n{{");
        if (arity == 2) text.AppendLine("    static virtual bool IsSymmetric => false;");
        text.AppendLine($"    bool Matches({string.Join(", ", Enumerable.Range(0, arity).Select(index => $"in T{index + 1} {Positions[index]}"))});\n}}\n");
        AppendBinding(text, arity, components, row);
        AppendFilter(text, arity, components, row, "Where");
        AppendFilter(text, arity, components, row, "Except");
        AppendProduct(text, arity, row);
        return text.ToString();
    }

    private static void Constraints(StringBuilder text, int arity)
    {
        for (int index = 1; index <= arity; index++) text.AppendLine($"    where T{index} : struct");
    }

    private static void AppendBinding(StringBuilder text, int arity, string components, string row)
    {
        text.AppendLine($"public ref struct ComponentRelation<TRelation, {components}> : IQueryRelation<{row}>")
            .AppendLine($"    where TRelation : struct, IRelation<{components}>, allows ref struct");
        Constraints(text, arity);
        text.AppendLine("{").AppendLine("    private TRelation _relation;");
        for (int index = 1; index <= arity; index++) text.AppendLine($"    private ReadLookup<T{index}> _read{index};");
        if (arity <= 2)
        {
            text.AppendLine("    private QueryChunk _firstChunk, _secondChunk;");
            text.AppendLine("    private ReadOnlySpan<T1> _firstValues;");
            if (arity == 2) text.AppendLine("    private ReadOnlySpan<T1> _reverseFirst;\n    private ReadOnlySpan<T2> _secondValues, _reverseSecond;");
        }
        text.AppendLine($"    public ComponentRelation(World world, TRelation relation)\n    {{\n        this = default;\n        _relation = relation;");
        for (int index = 1; index <= arity; index++) text.AppendLine($"        _read{index} = world.OpenRead<T{index}>();");
        text.AppendLine("    }");
        text.AppendLine("    public void Dispose()\n    {");
        for (int index = arity; index >= 1; index--) text.AppendLine($"        _read{index}.Dispose();");
        text.AppendLine("    }");
        text.AppendLine($"    public bool Matches(in {row} row)\n    {{");
        text.AppendLine("        if (" + string.Join(" || ", Enumerable.Range(1, arity).Select(index => $"!_read{index}.Has({(arity == 1 ? "row" : $"row.Item{index}")})")) + ") return false;");
        text.AppendLine("        return _relation.Matches(" + string.Join(", ", Enumerable.Range(1, arity).Select(index => $"in _read{index}.ReadKnown({(arity == 1 ? "row" : $"row.Item{index}")})")) + ");\n    }");
        text.AppendLine("    public void Bind(QueryChunk first, QueryChunk second)\n    {");
        if (arity <= 2)
        {
            text.AppendLine("        _firstChunk = first; _secondChunk = second;\n        first.TryRead<T1>(out _firstValues);");
            if (arity == 2) text.AppendLine("        second.TryRead<T2>(out _secondValues);\n        second.TryRead<T1>(out _reverseFirst);\n        first.TryRead<T2>(out _reverseSecond);");
        }
        text.AppendLine("    }");
        text.AppendLine($"    public bool Matches(in {row} row, int first, int second, bool reversed)\n    {{");
        if (arity == 1)
            text.AppendLine("        return !_firstValues.IsEmpty && _firstChunk.Has<T1>(first) && _relation.Matches(in _firstValues[first]);");
        else if (arity == 2)
        {
            text.AppendLine("        if (reversed && !(typeof(T1) == typeof(T2) && TRelation.IsSymmetric))\n        {\n            if (_reverseFirst.IsEmpty || _reverseSecond.IsEmpty || !_secondChunk.Has<T1>(second) || !_firstChunk.Has<T2>(first)) return false;\n            return _relation.Matches(in _reverseFirst[second], in _reverseSecond[first]);\n        }\n        if (_firstValues.IsEmpty || _secondValues.IsEmpty || !_firstChunk.Has<T1>(first) || !_secondChunk.Has<T2>(second)) return false;\n        return _relation.Matches(in _firstValues[first], in _secondValues[second]);");
        }
        else text.AppendLine("        return Matches(in row);");
        text.AppendLine("    }\n}\n");
    }

    private static void AppendFilter(StringBuilder text, int arity, string components, string row, string operation)
    {
        string binding = $"ComponentRelation<TRelation, {components}>";
        text.AppendLine($"public readonly struct Component{operation}<TEnumerable, TRelation, {components}> : IQueryRelationEnumerable<{row}>")
            .AppendLine($"    where TEnumerable : struct, IQueryRelationEnumerable<{row}>")
            .AppendLine($"    where TRelation : struct, IRelation<{components}>");
        Constraints(text, arity);
        text.AppendLine("{")
            .AppendLine("    private readonly TEnumerable _enumerable;\n    private readonly TRelation _relation;")
            .AppendLine($"    public Component{operation}(TEnumerable enumerable, TRelation relation) => (_enumerable, _relation) = (enumerable, relation);")
            .AppendLine("    public World World => _enumerable.World;\n    public int QueryCount => _enumerable.QueryCount;\n    public static bool ReadsFromSingleQuery => TEnumerable.ReadsFromSingleQuery;")
            .AppendLine("    public Query GetQuery(int position) => _enumerable.GetQuery(position);")
            .AppendLine("    public QueryDescription AddReads(QueryDescription definition, int position)\n    {\n        definition = _enumerable.AddReads(definition, position);");
        for (int index = 1; index <= arity; index++) text.AppendLine($"        if (position == {index - 1} || QueryCount <= 1) definition.Optional<T{index}>();");
        text.AppendLine("        return definition;\n    }")
            .AppendLine($"    public bool Enumerate<TOutput>(scoped RelationQueryViews queries, ref TOutput output)\n        where TOutput : struct, IQueryRelationOutput<{row}>, allows ref struct\n    {{")
            .AppendLine($"        using var relation = new {binding}(queries.World, _relation);")
            .AppendLine($"        var filtered = new RelationFilterOutput<{binding}, TOutput, {row}, {operation}Selection>(relation, new(ref output));")
            .AppendLine("        return _enumerable.Enumerate(queries, ref filtered);\n    }\n}\n");
    }

    private static void AppendProduct(StringBuilder text, int arity, string row)
    {
        string[] names = Positions.Take(arity).ToArray();
        string args = string.Join(", ", names.Select(name => $"Query {name}"));
        text.AppendLine($"public static partial class RelationQueries\n{{\n    public static RelationQuery<EntityProduct{arity}, {row}> Product(this World world, {args}) => new(new EntityProduct{arity}(world, {string.Join(", ", names)}));\n}}\n");
        text.AppendLine($"public readonly struct EntityProduct{arity} : IQueryRelationEnumerable<{row}>\n{{");
        foreach (string name in names) text.AppendLine($"    private readonly Query _{name};");
        text.AppendLine($"    public EntityProduct{arity}(World world, {args})\n    {{\n        World = world;");
        foreach (string name in names) text.AppendLine($"        _{name} = {name};");
        text.AppendLine($"    }}\n    public World World {{ get; }}\n    public int QueryCount => {arity};\n    public static bool ReadsFromSingleQuery => {(arity == 1 ? "true" : "false")};");
        text.AppendLine("    public Query GetQuery(int position) => position switch\n    {");
        for (int index = 0; index < arity; index++) text.AppendLine($"        {(index == arity - 1 ? "_" : index.ToString())} => _{names[index]},");
        text.AppendLine("    };\n    public QueryDescription AddReads(QueryDescription definition, int position) => definition;");
        text.AppendLine($"    public bool Enumerate<TOutput>(scoped RelationQueryViews queries, ref TOutput output)\n        where TOutput : struct, IQueryRelationOutput<{row}>, allows ref struct\n    {{");
        int indent = 8;
        for (int index = 0; index < arity; index++)
        {
            string position = char.ToUpperInvariant(names[index][0]) + names[index].Substring(1);
            text.AppendLine(new string(' ', indent) + $"foreach (QueryChunk {names[index]}Chunk in queries.{position})\n" + new string(' ', indent) + "{");
            indent += 4;
        }
        if (arity <= 2) text.AppendLine(new string(' ', indent) + $"if (TOutput.UsesBoundColumns) output.Bind(firstChunk, {(arity == 1 ? "firstChunk" : "secondChunk")});");
        foreach (string name in names)
        {
            text.AppendLine(new string(' ', indent) + $"for (int {name} = 0; {name} < {name}Chunk.Count; {name}++)\n" + new string(' ', indent) + "{");
            indent += 4;
        }
        string value = arity == 1 ? "firstChunk.Entities[first]" : "(" + string.Join(", ", names.Select(name => $"{name}Chunk.Entities[{name}]")) + ")";
        text.AppendLine(new string(' ', indent) + $"{(arity == 1 ? "Entity" : "var")} row = {value};");
        string added = arity <= 2 ? $"TOutput.UsesBoundColumns ? output.Add(in row, first, {(arity == 1 ? "first" : "second")}, false) : output.Add(in row)" : "output.Add(in row)";
        text.AppendLine(new string(' ', indent) + $"if (!({added})) return false;");
        for (int index = 0; index < arity * 2; index++) { indent -= 4; text.AppendLine(new string(' ', indent) + "}"); }
        text.AppendLine("        return true;\n    }\n}\n");
    }

    private static string GenerateViews()
    {
        string[] names = Positions.Select(name => char.ToUpperInvariant(name[0]) + name.Substring(1)).ToArray();
        var text = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace SomeEngine.ECS.Relations;\npublic readonly ref struct RelationQueryViews\n{\n");
        text.AppendLine("    public RelationQueryViews(World world, QueryScope access, QueryScope first, QueryScope second)\n        : this(world, access, first, second, default, default, default, default, default, default) { }");
        text.AppendLine("    public RelationQueryViews(World world, QueryScope access, " + string.Join(", ", Positions.Select(name => $"QueryScope {name}")) + ")\n    {\n        World = world; Access = access;");
        for (int index = 0; index < names.Length; index++) text.AppendLine($"        {names[index]} = {Positions[index]};");
        text.AppendLine("    }\n    public World World { get; }\n    public QueryScope Access { get; }");
        foreach (string name in names) text.AppendLine($"    public QueryScope {name} {{ get; }}");
        text.AppendLine("    internal RelationQueryViews WithQuery(int position, QueryScope query) => new(World, Access,");
        for (int index = 0; index < names.Length; index++) text.AppendLine($"        position == {index} ? query : {names[index]}{(index == names.Length - 1 ? ");" : ",")}");
        text.AppendLine("}");
        return text.ToString();
    }
}
