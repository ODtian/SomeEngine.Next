using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace SomeEngine.ECS.SourceGen;

[Generator]
public sealed class EcsGenerator : IIncrementalGenerator
{
    private static readonly SymbolDisplayFormat FullName = SymbolDisplayFormat.FullyQualifiedFormat.WithMiscellaneousOptions(
        SymbolDisplayFormat.FullyQualifiedFormat.MiscellaneousOptions | SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);
    internal static readonly DiagnosticDescriptor Shape = new("ECSG001", "Generated ECS declaration",
        "{0}", "ECS", DiagnosticSeverity.Error, true);
    internal static readonly DiagnosticDescriptor Writes = new("ECSG002", "Generated job state",
        "{0}", "ECS", DiagnosticSeverity.Error, true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var types = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is TypeDeclarationSyntax type && (type.BaseList is not null || type.AttributeLists.Count != 0),
            static (syntax, _) => syntax.SemanticModel.GetDeclaredSymbol((TypeDeclarationSyntax)syntax.Node) as INamedTypeSymbol)
            .Where(static type => type is not null).Collect();
        context.RegisterSourceOutput(types.Combine(context.CompilationProvider), static (output, input) =>
        {
            var all = input.Left;
            var seen = new HashSet<ISymbol>(SymbolEqualityComparer.Default);
            foreach (INamedTypeSymbol? type in all)
            {
                if (type is null || !seen.Add(type)) continue;
                bool entity = HasInterface(type, "SomeEngine.ECS.Systems.IJobEntity");
                bool chunk = HasInterface(type, "SomeEngine.ECS.Systems.IJobChunk");
                bool component = HasAttribute(type, "SomeEngine.ECS.GenerateComponentAttribute");
                bool codec = HasAttribute(type, "SomeEngine.ECS.Serialization.GenerateCodecAttribute");
                if (!entity && !chunk && !component && !codec) continue;
                if (type.TypeKind != TypeKind.Struct || type.IsRefLikeType || !Partial(type))
                { Error(output, type, "Declare generated ECS values and jobs as partial structs."); continue; }
                if (entity || chunk) JobGenerator.Emit(output, type, entity, input.Right);
                if (component || codec) ValueGenerator.Emit(output, type, component, codec);
            }
        });
    }

    internal static bool Partial(INamedTypeSymbol type)
    {
        for (INamedTypeSymbol? current = type; current is not null; current = current.ContainingType)
            if (!current.DeclaringSyntaxReferences.Any(reference => reference.GetSyntax() is TypeDeclarationSyntax syntax
                && syntax.Modifiers.Any(SyntaxKind.PartialKeyword))) return false;
        return true;
    }
    internal static bool HasAttribute(ISymbol type, string attribute)
        => type.GetAttributes().Any(value => value.AttributeClass?.ToDisplayString() == attribute);
    internal static bool HasInterface(ITypeSymbol type, string name)
        => type is INamedTypeSymbol named && (named.ToDisplayString() == name || named.AllInterfaces.Any(value => value.ToDisplayString() == name));
    internal static string Name(ITypeSymbol type) => type.ToDisplayString(FullName);
    internal static string Identifier(string name) => "@" + name;
    internal static void Error(SourceProductionContext output, ISymbol type, string message, bool writes = false)
        => output.ReportDiagnostic(Diagnostic.Create(writes ? Writes : Shape, type.Locations.FirstOrDefault(), message));
    internal static void Add(SourceProductionContext output, INamedTypeSymbol type, string suffix, string source)
    {
        string hint = new string(type.ToDisplayString().Select(character => char.IsLetterOrDigit(character) ? character : '_').ToArray());
        output.AddSource(hint + "." + suffix + ".g.cs", SourceText.From(source, Encoding.UTF8));
    }

    internal static string Wrap(INamedTypeSymbol type, string interfaces, string body)
    {
        var text = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        if (!type.ContainingNamespace.IsGlobalNamespace) text.Append("namespace ").Append(type.ContainingNamespace.ToDisplayString()).Append(" {\n");
        var parents = new Stack<INamedTypeSymbol>();
        for (INamedTypeSymbol? parent = type.ContainingType; parent is not null; parent = parent.ContainingType) parents.Push(parent);
        int depth = parents.Count;
        while (parents.Count != 0) text.Append(Declaration(parents.Pop(), "")).Append(" {\n");
        text.Append(Declaration(type, interfaces)).Append(" {\n").Append(body).Append("\n}\n");
        for (int i = 0; i < depth; i++) text.Append("}\n");
        if (!type.ContainingNamespace.IsGlobalNamespace) text.Append("}\n");
        return text.ToString();
    }

    private static string Declaration(INamedTypeSymbol type, string interfaces)
    {
        var text = new StringBuilder();
        text.Append(type.DeclaredAccessibility switch
        {
            Accessibility.Public => "public ", Accessibility.Private => "private ",
            Accessibility.Protected => "protected ", Accessibility.ProtectedOrInternal => "protected internal ",
            Accessibility.ProtectedAndInternal => "private protected ", _ => "internal "
        });
        if (type.IsStatic) text.Append("static ");
        if (type.IsReadOnly) text.Append("readonly ");
        text.Append("partial ").Append(type.IsRecord ? type.TypeKind == TypeKind.Struct ? "record struct " : "record class "
            : type.TypeKind == TypeKind.Struct ? "struct " : "class ").Append(Identifier(type.Name));
        if (type.TypeParameters.Length != 0) text.Append('<').Append(string.Join(", ", type.TypeParameters.Select(value => Identifier(value.Name)))).Append('>');
        if (interfaces.Length != 0) text.Append(" : ").Append(interfaces);
        foreach (ITypeParameterSymbol parameter in type.TypeParameters)
        {
            var constraints = new List<string>();
            if (parameter.HasUnmanagedTypeConstraint) constraints.Add("unmanaged");
            else if (parameter.HasValueTypeConstraint) constraints.Add("struct");
            else if (parameter.HasReferenceTypeConstraint) constraints.Add("class");
            else if (parameter.HasNotNullConstraint) constraints.Add("notnull");
            constraints.AddRange(parameter.ConstraintTypes.Select(Name));
            if (parameter.HasConstructorConstraint) constraints.Add("new()");
            if (constraints.Count != 0) text.Append(" where ").Append(Identifier(parameter.Name)).Append(" : ").Append(string.Join(", ", constraints));
        }
        return text.ToString();
    }
}
