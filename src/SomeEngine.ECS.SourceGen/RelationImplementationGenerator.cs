using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace SomeEngine.ECS.SourceGen;

[Generator]
public sealed class RelationImplementationGenerator : IIncrementalGenerator
{
    private const string RelationsNamespace = "SomeEngine.ECS.Relations";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var implementations = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is StructDeclarationSyntax or RecordDeclarationSyntax,
                static (syntax, _) => GetImplementation(syntax))
            .Where(static type => type is not null)
            .Select(static (type, _) => type!)
            .Collect();
        context.RegisterSourceOutput(implementations, static (output, types) => Generate(output, types));
    }

    private static INamedTypeSymbol? GetImplementation(GeneratorSyntaxContext context)
    {
        if (context.SemanticModel.GetDeclaredSymbol(context.Node) is not INamedTypeSymbol type || !type.IsValueType)
            return null;
        return type.AllInterfaces.Any(IsKeyRelation) ? type : null;
    }

    private static bool IsKeyRelation(INamedTypeSymbol type) =>
        type.Name == "IKeyRelation" && type.Arity == 3 &&
        type.ContainingNamespace.ToDisplayString() == RelationsNamespace;

    private static void Generate(SourceProductionContext context, ImmutableArray<INamedTypeSymbol> types)
    {
        var seen = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        foreach (var type in types)
        {
            if (!seen.Add(type))
                continue;
            var arguments = type.AllInterfaces.First(IsKeyRelation).TypeArguments;
            string implementation = FullName(type);
            string relation = FullName(arguments[0]);
            string component = FullName(arguments[1]);
            string key = FullName(arguments[2]);
            string access = IsPublic(type) ? "public" : "internal";
            string row = "(global::SomeEngine.ECS.Entities.Entity, global::SomeEngine.ECS.Entities.Entity)";
            var parameters = TypeParameters(type).ToArray();
            var text = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
            if (!type.ContainingNamespace.IsGlobalNamespace)
                text.Append("namespace ").Append(type.ContainingNamespace.ToDisplayString()).AppendLine(";");
            text.AppendLine("public static partial class RelationQueryExtensions\n{");
            foreach (string operation in new[] { "Where", "Except" })
            {
                AppendEntry(text, access, operation, relation, implementation, component, key, row, parameters, null, null);
                AppendEntry(text, access, operation, relation, implementation, component, key, row, parameters,
                    "EntityPairsWithin", "KeyPairsWithin");
                AppendEntry(text, access, operation, relation, implementation, component, key, row, parameters,
                    "EntityProduct2", "KeyProduct2");
                AppendEntry(text, access, operation, relation, implementation, component, key, row, parameters,
                    "EntityPairsBetween", "KeyPairsBetween");
            }
            text.AppendLine("}");
            string hint = type.ToDisplayString().Replace('.', '_').Replace('<', '_').Replace('>', '_').Replace(',', '_').Replace(' ', '_');
            context.AddSource($"RelationImplementation_{hint}.g.cs", text.ToString());
        }
    }

    private static void AppendEntry(StringBuilder text, string access, string operation, string relation,
        string implementation, string component, string key, string row, ITypeParameterSymbol[] parameters,
        string? source, string? pairing)
    {
        string sourceType = "TEnumerable";
        while (parameters.Any(parameter => parameter.Name == sourceType))
            sourceType += "Source";
        string[] genericTypes = (source is null ? new[] { sourceType } : Array.Empty<string>())
            .Concat(parameters.Select(parameter => parameter.Name)).ToArray();
        string generic = genericTypes.Length == 0 ? "" : $"<{string.Join(", ", genericTypes)}>";
        string binding = source is null
            ? $"global::{RelationsNamespace}.KeyFilter<{sourceType}, {relation}, {implementation}, {component}, {key}>"
            : $"global::{RelationsNamespace}.KeyPairs<global::{RelationsNamespace}.{pairing}, {relation}, {implementation}, {component}, {key}>";
        string enumerable = source is null ? sourceType : $"global::{RelationsNamespace}.{source}";
        text.Append("    ").Append(access).Append(" static global::").Append(RelationsNamespace)
            .Append(".RelationQuery<").Append(binding).Append(", ").Append(row).Append("> ").Append(operation).Append(generic).AppendLine("(")
            .Append("        this global::").Append(RelationsNamespace).Append(".RelationQuery<")
            .Append(enumerable).Append(", ").Append(row).AppendLine("> source,")
            .Append("        ").Append(relation).AppendLine(" relation,")
            .Append("        ").Append(implementation).AppendLine(" implementation)");
        if (source is null)
            text.Append("        where ").Append(sourceType).Append(" : struct, global::").Append(RelationsNamespace)
                .Append(".IQueryRelationEnumerable<").Append(row).AppendLine(">");
        foreach (var parameter in parameters)
            AppendConstraints(text, parameter);
        text.Append("        => new(new ").Append(binding).Append('(');
        if (source is null)
            text.Append("source.Enumerable, ");
        else
            text.Append("source.Enumerable.World, source.Enumerable.GetQuery(0), source.Enumerable.GetQuery(")
                .Append(source == "EntityPairsWithin" ? "0" : "1").Append("), ");
        text.Append("relation, implementation, ").Append(operation == "Except" ? "true" : "false").AppendLine("));\n");
    }

    private static string FullName(ITypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

    private static IEnumerable<ITypeParameterSymbol> TypeParameters(INamedTypeSymbol type) =>
        (type.ContainingType is null ? Enumerable.Empty<ITypeParameterSymbol>() : TypeParameters(type.ContainingType))
        .Concat(type.TypeParameters);

    private static bool IsPublic(INamedTypeSymbol type) =>
        type.DeclaredAccessibility == Accessibility.Public && (type.ContainingType is null || IsPublic(type.ContainingType));

    private static void AppendConstraints(StringBuilder text, ITypeParameterSymbol parameter)
    {
        var constraints = new List<string>();
        if (parameter.HasUnmanagedTypeConstraint) constraints.Add("unmanaged");
        else if (parameter.HasValueTypeConstraint) constraints.Add("struct");
        else if (parameter.HasReferenceTypeConstraint) constraints.Add("class");
        else if (parameter.HasNotNullConstraint) constraints.Add("notnull");
        constraints.AddRange(parameter.ConstraintTypes.Select(FullName));
        if (parameter.HasConstructorConstraint) constraints.Add("new()");
        if (constraints.Count > 0)
            text.Append("        where ").Append(parameter.Name).Append(" : ").AppendLine(string.Join(", ", constraints));
    }
}
