using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace SomeEngine.ECS.SourceGen;

[Generator]
public sealed class SpatialRelationGenerator : IIncrementalGenerator
{
    private const string Relations = "global::SomeEngine.ECS.Relations.";
    private const string Physics = "global::SomeEngine.Physics.";
    private const string Row = "(global::SomeEngine.ECS.Entities.Entity, global::SomeEngine.ECS.Entities.Entity)";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var types = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is StructDeclarationSyntax or RecordDeclarationSyntax,
                static (syntax, _) => GetType(syntax))
            .Where(static type => type is not null).Select(static (type, _) => type!).Collect();
        var hasPhysics = context.CompilationProvider.Select(static (compilation, _) =>
            compilation.GetTypeByMetadataName("SomeEngine.Physics.CollisionCandidates`2") is not null);
        context.RegisterSourceOutput(types.Combine(hasPhysics), static (output, input) =>
        {
            if (input.Right)
                Generate(output, input.Left);
        });
    }

    private static INamedTypeSymbol? GetType(GeneratorSyntaxContext context) =>
        context.SemanticModel.GetDeclaredSymbol(context.Node) is INamedTypeSymbol type && type.IsValueType &&
        type.AllInterfaces.Any(IsSupported) ? type : null;

    private static bool IsSupported(INamedTypeSymbol type) =>
        type.ContainingNamespace.ToDisplayString() == "SomeEngine.ECS.Relations" &&
        (type.Name == "IRelation" && type.Arity == 2 ||
            (type.Name == "IKeyRelation" || type.Name == "IBitmapRelation") && type.Arity == 3);

    private static void Generate(SourceProductionContext context, ImmutableArray<INamedTypeSymbol> types)
    {
        var seen = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        foreach (var type in types)
        {
            if (!seen.Add(type))
                continue;
            INamedTypeSymbol capability = type.AllInterfaces.First(IsSupported);
            var parameters = RelationTypeSyntax.TypeParameters(type).ToArray();
            string typeName = FullName(type);
            bool key = capability.Name == "IKeyRelation";
            bool bitmap = capability.Name == "IBitmapRelation";
            string relation = key || bitmap ? FullName(capability.TypeArguments[0]) : typeName;
            string atom;
            string pairAtom;
            if (key)
            {
                atom = $"{Physics}SpatialKeyFilter<{relation}, {typeName}, {FullName(capability.TypeArguments[1])}, {FullName(capability.TypeArguments[2])}>";
                pairAtom = $"{Physics}CollisionKeyFilter<{relation}, {typeName}, {FullName(capability.TypeArguments[1])}, {FullName(capability.TypeArguments[2])}>";
            }
            else if (bitmap)
            {
                string permission = FullName(capability.TypeArguments[2]);
                string proof = permission == Relations + "OneWayPermission" ? "OneWaySpatialPermission" :
                    permission == Relations + "MutualPermission" ? "MutualSpatialPermission" : "UnknownSpatialPermission";
                atom = $"{Physics}SpatialBitmapFilter<{relation}, {typeName}, {FullName(capability.TypeArguments[1])}, {permission}, {Physics}{proof}>";
                pairAtom = $"{Physics}CollisionBitmapFilter<{relation}, {typeName}, {FullName(capability.TypeArguments[1])}, {permission}>";
            }
            else
            {
                atom = $"{Physics}SpatialComponentFilter<{relation}, {FullName(capability.TypeArguments[0])}, {FullName(capability.TypeArguments[1])}>";
                pairAtom = $"{Physics}CollisionComponentFilter<{relation}, {FullName(capability.TypeArguments[0])}, {FullName(capability.TypeArguments[1])}>";
            }
            var text = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
            if (!type.ContainingNamespace.IsGlobalNamespace)
                text.Append("namespace ").Append(type.ContainingNamespace.ToDisplayString()).AppendLine(";");
            text.AppendLine("public static partial class RelationQueryExtensions\n{");
            foreach (string operation in new[] { "Where", "Except" })
            {
                AppendEntry(text, type, parameters, operation, relation, key || bitmap ? typeName : null, atom, false);
                AppendEntry(text, type, parameters, operation, relation, key || bitmap ? typeName : null, atom, true);
                AppendPairEntry(text, type, parameters, operation, relation, key || bitmap ? typeName : null, pairAtom);
            }
            text.AppendLine("}");
            string hint = type.ToDisplayString().Replace('.', '_').Replace('<', '_').Replace('>', '_').Replace(',', '_').Replace(' ', '_');
            context.AddSource($"SpatialRelation_{hint}.g.cs", text.ToString());
        }
    }

    private static void AppendPairEntry(StringBuilder text, INamedTypeSymbol type, ITypeParameterSymbol[] parameters,
        string operation, string relation, string? implementation, string atom)
    {
        var used = parameters.Select(parameter => parameter.Name).ToList();
        string source = Name("TPairSource", used);
        string partition = Name("TPairPartition", used);
        string previous = Name("TPairFilter", used);
        string appended = operation == "Except" ? $"{Physics}CollisionPairExcept<{atom}>" : atom;
        string filter = $"{Physics}CollisionPairAnd<{previous}, {appended}>";
        string input = $"{Physics}CollisionPairCandidates<{source}, {partition}, {previous}>";
        string result = $"{Physics}CollisionPairCandidates<{source}, {partition}, {filter}>";
        var generics = new[] { source, partition, previous }.Concat(parameters.Select(parameter => parameter.Name));
        text.Append("    ").Append(RelationTypeSyntax.IsPublic(type) ? "public" : "internal").Append(" static ")
            .Append(Relations).Append("RelationQuery<").Append(result).Append(", ").Append(Row).Append("> ")
            .Append(operation).Append('<').Append(string.Join(", ", generics)).AppendLine(">(")
            .Append("        this ").Append(Relations).Append("RelationQuery<").Append(input).Append(", ")
            .Append(Row).AppendLine("> source,")
            .Append("        ").Append(relation).Append(" relation");
        if (implementation is not null)
            text.AppendLine(",").Append("        ").Append(implementation).Append(" implementation");
        text.AppendLine(")")
            .Append("        where ").Append(source).Append(" : struct, ").Append(Physics)
            .Append("ICollisionPartitionEnumerable<").Append(partition).AppendLine(">")
            .Append("        where ").Append(partition).AppendLine(" : struct")
            .Append("        where ").Append(previous).Append(" : struct, ").Append(Physics)
            .AppendLine("ICollisionPairFilter");
        foreach (var parameter in parameters)
            RelationTypeSyntax.AppendConstraints(text, parameter);
        string expression = implementation is null ? $"new {atom}(relation)" : $"new {atom}(relation, implementation)";
        if (operation == "Except")
            expression = $"new {appended}({expression})";
        text.Append("        => new(new ").Append(result).Append("(source.Enumerable.Source, new ")
            .Append(filter).Append("(source.Enumerable.Filter, ").Append(expression).AppendLine(")));\n");
    }

    private static void AppendEntry(StringBuilder text, INamedTypeSymbol type, ITypeParameterSymbol[] parameters,
        string operation, string relation, string? implementation, string atom, bool composed)
    {
        var used = parameters.Select(parameter => parameter.Name).ToList();
        string geometry = Name("TSpatialGeometry", used);
        string reader = Name("TSpatialBoundsReader", used);
        string previous = Name("TSpatialFilter", used);
        string previousResults = Name("TSpatialResults", used);
        string group = Physics + "GroupMatch";
        string appended = operation == "Except" ? $"{Physics}SpatialExcept<{atom}, {group}>" : atom;
        string filter = composed ? $"{Physics}SpatialAnd<{previous}, {appended}, {previousResults}, {group}>" : appended;
        string results = composed ? $"global::System.ValueTuple<{previousResults}, {group}>" : group;
        string source = composed
            ? $"{Physics}SpatialCandidates<{geometry}, {reader}, {previous}, {previousResults}>"
            : $"{Physics}CollisionCandidates<{geometry}, {reader}>";
        string result = $"{Physics}SpatialCandidates<{geometry}, {reader}, {filter}, {results}>";
        var generics = new List<string> { geometry, reader };
        if (composed)
            generics.AddRange(new[] { previous, previousResults });
        generics.AddRange(parameters.Select(parameter => parameter.Name));
        text.Append("    ").Append(RelationTypeSyntax.IsPublic(type) ? "public" : "internal").Append(" static ").Append(Relations)
            .Append("RelationQuery<").Append(result).Append(", ").Append(Row).Append("> ").Append(operation)
            .Append('<').Append(string.Join(", ", generics)).AppendLine(">(")
            .Append("        this ").Append(Relations).Append("RelationQuery<").Append(source).Append(", ").Append(Row)
            .AppendLine("> source,").Append("        ").Append(relation).Append(" relation");
        if (implementation is not null)
            text.AppendLine(",").Append("        ").Append(implementation).Append(" implementation");
        text.AppendLine(")")
            .Append("        where ").Append(geometry).AppendLine(" : struct")
            .Append("        where ").Append(reader).Append(" : struct, ").Append(Physics)
            .Append("ICollisionBoundsReader<").Append(geometry).AppendLine(">");
        if (composed)
        {
            text.Append("        where ").Append(previous).Append(" : struct, ").Append(Physics)
                .Append("ISpatialFilter<").Append(previousResults).AppendLine(">")
                .Append("        where ").Append(previousResults).AppendLine(" : unmanaged");
        }
        foreach (var parameter in parameters)
            RelationTypeSyntax.AppendConstraints(text, parameter);
        string expression = implementation is null ? $"new {atom}(relation)" :
            $"new {atom}(source.Enumerable.Tree, relation, implementation)";
        if (operation == "Except")
            expression = $"new {appended}({expression})";
        if (composed)
            expression = $"new {filter}(source.Enumerable.Filter, {expression})";
        text.Append("        => new(new ").Append(result).Append("(source.Enumerable")
            .Append(composed ? ".Source" : "").Append(", ").Append(expression).AppendLine("));\n");
    }

    private static string Name(string name, List<string> used)
    {
        while (used.Contains(name))
            name += "Source";
        used.Add(name);
        return name;
    }

    private static string FullName(ITypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
}
