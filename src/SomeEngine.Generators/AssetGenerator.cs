using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace SomeEngine.Generators;

internal static class AssetGenerator
{
    private static readonly DiagnosticDescriptor InvalidFields = new(
        "SEAS001", "Invalid asset fields", "Asset fields '{0}': {1}", "SomeEngine.Assets",
        DiagnosticSeverity.Error, true);

    private static void Emit(SourceProductionContext output, INamedTypeSymbol fields,
        INamedTypeSymbol type, string suffix, bool nestedAsset)
    {
        string data = fields.ToDisplayString(NullableTypeFormat);
        string domain = type.ToDisplayString(NullableTypeFormat);
        var properties = fields.GetMembers().OfType<IPropertySymbol>().Where(p =>
            !p.IsStatic && p.GetMethod is not null && p.SetMethod is not null && p.Name is not "AssetGuid" and not "Name").ToArray();
        var buffers = properties.Where(p => IsByteMemory(p.Type)).ToArray();
        var code = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        if (!type.ContainingNamespace.IsGlobalNamespace)
            code.Append("namespace ").Append(type.ContainingNamespace.ToDisplayString()).AppendLine(";");
        code.Append(type.DeclaredAccessibility == Accessibility.Public ? "public " : "internal ")
            .Append("partial class ").Append(type.Name).AppendLine(" {");
        code.Append("public sealed partial class Asset : global::SomeEngine.Assets.Asset<").Append(domain).AppendLine("> {");
        code.Append("public const string FileType = ").Append(Literal(type.ToDisplayString())).AppendLine(";");
        code.Append("public const string PathSuffix = ").Append(Literal(suffix)).AppendLine(";");
        code.Append("public static ulong SchemaHash => ").Append(data).AppendLine(".SchemaFingerprint;");
        code.Append("public static global::SomeEngine.Serialization.Containers.BinaryWireTypeDescriptor WireType => new(")
            .Append(data).Append(".TypeId, SchemaHash, ").Append(data).Append(".Compatibility, ").Append(data).AppendLine(".SchemaEpoch);");
        code.AppendLine("private global::SomeEngine.Serialization.Containers.SharedData<Fields> _fields;");
        code.AppendLine("private sealed class Fields {");
        foreach (var property in properties)
        {
            if (IsByteMemory(property.Type))
                code.Append("internal global::SomeEngine.Serialization.Containers.SharedBytes? ").Append(property.Name).AppendLine(";");
            else
                code.Append("internal ").Append(property.Type.ToDisplayString(NullableTypeFormat)).Append(' ').Append(property.Name).AppendLine(";");
        }
        code.Append("internal Fields(").Append(data).AppendLine(" values) {");
        foreach (var property in properties)
            code.Append(property.Name).Append(" = values.").Append(IsByteMemory(property.Type) ? "Retain" + property.Name + "Bytes()" : property.Name).AppendLine(";");
        code.AppendLine("}");
        code.AppendLine("internal Fields Copy() { var copy = (Fields)MemberwiseClone();");
        foreach (var buffer in buffers) code.Append("copy.").Append(buffer.Name).Append(" = ").Append(buffer.Name).AppendLine("?.Retain();");
        code.AppendLine("return copy; }");
        code.AppendLine("internal void Release() {");
        foreach (var buffer in buffers) code.Append(buffer.Name).AppendLine("?.Dispose();");
        code.AppendLine("} }");
        code.Append("public Asset(global::SomeEngine.Assets.AssetId<").Append(domain).AppendLine("> id = default) : base(id) {");
        code.Append("var values = new ").Append(data).AppendLine("(); _fields = new(new Fields(values));");
        if (fields.GetMembers("Name").Length != 0) code.AppendLine("Name = values.Name ?? string.Empty;");
        if (buffers.Length != 0) code.AppendLine("values.Dispose();");
        code.AppendLine("}");
        code.Append("private Asset(Asset source, global::SomeEngine.Assets.AssetId<").Append(domain).AppendLine("> id) : base(source, id) { _fields = source._fields.Retain(); }");
        code.Append("public Asset Duplicate(global::SomeEngine.Assets.AssetId<").Append(domain).AppendLine("> id = default) { lock (Access) { RequireIdle(); return new(this, id); } }");
        code.AppendLine("private Fields WriteFields() { RequireIdle(); if (!_fields.IsShared) return _fields.Read; var copy = _fields.Read.Copy(); if (_fields.Release(out var previous)) previous.Release(); _fields = new(copy); return copy; }");
        code.AppendLine("protected override void ReleaseFields() { if (_fields.Release(out var fields)) fields.Release(); }");
        foreach (var property in properties)
        {
            string name = property.Name;
            string propertyType = property.Type.ToDisplayString(NullableTypeFormat);
            code.Append("public ").Append(propertyType).Append(' ').Append(name).Append(" { get { lock (Access) { RequireIdle(); return _fields.Read.").Append(name)
                .Append(IsByteMemory(property.Type) ? "?.Read" : "").Append("; } } set { lock (Access) { var fields = WriteFields(); ");
            if (IsByteMemory(property.Type))
                code.Append("var previous = fields.").Append(name).Append("; fields.").Append(name).Append(" = value.HasValue ? new(value.Value) : null; previous?.Dispose();");
            else code.Append("fields.").Append(name).Append(" = value;");
            code.AppendLine(" } } }");
            if (IsByteMemory(property.Type)) EmitByteAccess(code, property);
        }
        code.Append("internal ").Append(data).AppendLine(" CopyValues() { lock (Access) { RequireIdle(); var fields = _fields.Read;");
        code.Append("var values = new ").Append(data).AppendLine(" { AssetGuid = Id.Value.ToString(),");
        if (fields.GetMembers("Name").Length != 0) code.AppendLine("Name = Name,");
        foreach (var property in properties.Where(p => !IsByteMemory(p.Type))) code.Append(property.Name).Append(" = fields.").Append(property.Name).AppendLine(",");
        code.AppendLine("};");
        foreach (var buffer in buffers) code.Append("values.Attach").Append(buffer.Name).Append("Bytes(fields.").Append(buffer.Name).AppendLine("?.Retain());");
        code.AppendLine("return values; } }");
        code.AppendLine("public global::SomeEngine.Assets.AssetEntry Describe() { lock (Access) { RequireIdle(); return Describe(FileType, SchemaHash, References()); } }");
        code.AppendLine("private global::System.Collections.Generic.IEnumerable<global::System.Guid> References() {");
        int referenceIndex = 0;
        foreach (var property in properties)
        {
            var declaration = type.GetMembers(property.Name).OfType<IPropertySymbol>().FirstOrDefault();
            EmitReferences(code, property.Type, "_fields.Read." + property.Name,
                declaration?.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == "SomeEngine.Assets.AssetReferenceAttribute") == true,
                new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default), ref referenceIndex);
        }
        code.AppendLine("yield break; }");
        code.AppendLine("public async global::System.Threading.Tasks.ValueTask<global::SomeEngine.Assets.AssetEntry> SaveAsync(string path, global::System.Threading.CancellationToken cancellationToken = default) {");
        code.AppendLine("using var copy = Duplicate();");
        code.Append(buffers.Length == 0 ? "var" : "using var").AppendLine(" values = copy.CopyValues();");
        if (fields.GetMembers("CreateWriterAsync").Length != 0)
            code.Append("var writer = await ").Append(data).AppendLine(".CreateWriterAsync(values, copy.Source, cancellationToken).ConfigureAwait(false);");
        else if (fields.GetMembers("CreateWriter").Length != 0)
            code.Append("var writer = ").Append(data).AppendLine(".CreateWriter(values);");
        else
        {
            code.AppendLine("var writer = global::SomeEngine.Serialization.Containers.BinaryDocumentWriter.Create(values);");
            foreach (var buffer in buffers)
            {
                AttributeData? chunk = buffer.GetAttributes().FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == "SomeEngine.Serialization.BinaryChunkAttribute");
                if (chunk is null) continue;
                string key = chunk.ConstructorArguments[0].Value!.ToString();
                string length = chunk.ConstructorArguments[1].Value!.ToString();
                code.Append("if (values.").Append(buffer.Name).Append(" is { } bytes").Append(buffer.Name).AppendLine(") {");
                code.Append("if (values.").Append(key).Append(" == 0) values.").Append(key).Append(" = global::SomeEngine.Serialization.BinaryFieldKey.FromName(")
                    .Append(Literal(type.ToDisplayString() + "." + buffer.Name)).AppendLine(");");
                code.Append("values.").Append(length).Append(" = checked((ulong)bytes").Append(buffer.Name).AppendLine(".Length);");
                code.Append("writer.AddChunk(values.").Append(key).Append(", bytes").Append(buffer.Name).AppendLine(", ByteSchema);");
                code.Append("} else if (values.").Append(length).Append(" != 0) { await writer.AddChunkAsync(values.").Append(key)
                    .AppendLine(", copy.Source ?? throw new global::System.InvalidOperationException(\"The asset has no source for these bytes.\"), cancellationToken).ConfigureAwait(false); }");
            }
        }
        code.AppendLine("return await copy.SaveAsync(writer, path, PathSuffix, copy.Describe(), cancellationToken).ConfigureAwait(false); }");
        code.Append("private static Asset Read(global::SomeEngine.Serialization.Containers.BinaryDocument document, string path, global::SomeEngine.Assets.AssetId<").Append(domain).AppendLine("> expected = default) {");
        code.Append(buffers.Length == 0 ? "var" : "using var").Append(" values = document.ReadRoot<").Append(data).AppendLine(">();");
        code.AppendLine("if (!global::System.Guid.TryParse(values.AssetGuid, out var id) || id == global::System.Guid.Empty || (!expected.IsEmpty && id != expected.Value)) throw new global::System.IO.InvalidDataException(\"The asset file has a different or empty ID.\");");
        code.Append("var asset = new Asset(new global::SomeEngine.Assets.AssetId<").Append(domain).AppendLine(">(id));");
        code.AppendLine("asset.ReleaseFields(); asset._fields = new(new Fields(values));");
        if (fields.GetMembers("Name").Length != 0) code.AppendLine("asset.Name = values.Name ?? string.Empty;");
        code.AppendLine("asset.AttachSource(document); asset.SetSourcePath(path); return asset; }");
        code.Append("public static async global::System.Threading.Tasks.ValueTask<Asset> OpenAsync(global::SomeEngine.Assets.AssetLoader loader, global::SomeEngine.Assets.AssetId<").Append(domain).AppendLine("> id, global::System.Threading.CancellationToken cancellationToken = default) {");
        code.AppendLine("var source = await loader.OpenSourceAsync(id, FileType, WireType, cancellationToken).ConfigureAwait(false); await using var document = source.Document; return Read(document, source.Path, id); }");
        code.AppendLine("public static async global::System.Threading.Tasks.ValueTask<Asset> OpenAsync(string path, global::System.Threading.CancellationToken cancellationToken = default) { await using var document = await OpenFileAsync(path, PathSuffix, WireType, cancellationToken).ConfigureAwait(false); return Read(document, global::System.IO.Path.GetFullPath(path)); }");
        var load = type.GetMembers("CreateAsync").OfType<IMethodSymbol>().Where(m => m.IsStatic && m.Parameters.Length >= 2).OrderBy(m => m.Parameters.Length).FirstOrDefault();
        if (load is not null)
        {
            bool loader = load.Parameters.Any(p => p.Type.ToDisplayString() == "SomeEngine.Assets.AssetLoader");
            code.Append("public global::System.Threading.Tasks.ValueTask<").Append(domain).Append("> LoadAsync(");
            if (loader) code.Append("global::SomeEngine.Assets.AssetLoader loader, ");
            code.Append("global::System.Threading.CancellationToken cancellationToken = default) => ").Append(domain).Append(".CreateAsync(this, ").Append(loader ? "loader, " : "").AppendLine("cancellationToken);");
        }
        else if (type.GetMembers().OfType<IPropertySymbol>().All(p => !IsPartial(p)))
            code.Append("public global::System.Threading.Tasks.ValueTask<").Append(domain).Append("> LoadAsync(global::System.Threading.CancellationToken cancellationToken = default) { cancellationToken.ThrowIfCancellationRequested(); return global::System.Threading.Tasks.ValueTask.FromResult(").Append(domain).AppendLine(".CreateValueGenerated(CopyValues())); }");
        code.AppendLine("} }");
        output.AddSource(type.Name + ".Asset.g.cs", code.ToString());
    }

    private static void EmitReferences(StringBuilder code, ITypeSymbol type, string expression,
        bool reference, HashSet<ITypeSymbol> visited, ref int index)
    {
        if (reference && type.ToDisplayString() == "System.Guid")
        {
            code.Append("yield return ").Append(expression).AppendLine(";");
            return;
        }
        if (type.SpecialType == SpecialType.System_String)
        {
            if (reference) code.Append("if (!string.IsNullOrEmpty(").Append(expression).Append(")) yield return global::System.Guid.Parse(").Append(expression).AppendLine(");");
            return;
        }
        if (type is not INamedTypeSymbol named || !visited.Add(type)) return;
        var enumerable = named.AllInterfaces.FirstOrDefault(i => i.OriginalDefinition.ToDisplayString() == "System.Collections.Generic.IEnumerable<T>");
        var body = new StringBuilder();
        string local = "reference" + index++;
        if (enumerable is not null)
        {
            EmitReferences(body, enumerable.TypeArguments[0], local, reference, visited, ref index);
            if (body.Length != 0) code.Append("if (").Append(expression).Append(" is { } collection").Append(local)
                .Append(") foreach (var ").Append(local).Append(" in collection").Append(local).AppendLine(") {").Append(body).AppendLine("}");
        }
        else
        {
            foreach (var property in named.GetMembers().OfType<IPropertySymbol>().Where(p => !p.IsStatic && p.GetMethod is not null && p.DeclaredAccessibility == Accessibility.Public))
                EmitReferences(body, property.Type, local + "." + property.Name,
                    property.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == "SomeEngine.Assets.AssetReferenceAttribute"), visited, ref index);
            if (body.Length != 0) code.Append("if (").Append(expression).Append(" is { } ").Append(local).AppendLine(") {").Append(body).AppendLine("}");
        }
        visited.Remove(type);
    }

    private static void EmitByteAccess(StringBuilder code, IPropertySymbol property)
    {
        string name = property.Name;
        code.Append("public global::SomeEngine.Serialization.Containers.BufferRead? Read").Append(name).Append("() { lock (Access) { RequireIdle(); return _fields.Read.").Append(name).AppendLine(" is { } bytes ? new(bytes) : null; } }");
        if (!property.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == "SomeEngine.Serialization.BinaryChunkAttribute")) return;
        code.Append("public ByteEdit Write").Append(name).Append("() { lock (Access) { var fields = WriteFields(); return BeginByteEdit((fields.").Append(name).AppendLine(" ?? throw new global::System.InvalidOperationException(\"Read these bytes before editing them.\")).Write()); } }");
        code.Append("public async global::System.Threading.Tasks.ValueTask<global::SomeEngine.Serialization.Containers.BufferRead> Read").Append(name).AppendLine("Async(global::System.Threading.CancellationToken cancellationToken = default) {");
        code.AppendLine("using var copy = Duplicate();");
        code.Append("if (copy.Read").Append(name).AppendLine("() is { } bytes) return bytes;");
        code.AppendLine("await using var source = copy.RetainSource() ?? throw new global::System.InvalidOperationException(\"The asset has no source for these bytes.\");");
        code.Append("using var values = copy.CopyValues(); return new(await source.CopyChunkAsync(values.").Append(name).AppendLine("Chunk, cancellationToken).ConfigureAwait(false)); }");
        code.Append("public async global::System.Threading.Tasks.ValueTask<ByteEdit> Write").Append(name).AppendLine("Async(global::System.Threading.CancellationToken cancellationToken = default) {");
        code.Append("lock (Access) { RequireIdle(); if (_fields.Read.").Append(name).Append(" is not null) return Write").Append(name).AppendLine("(); }");
        code.AppendLine("using var copy = Duplicate(); await using var source = copy.RetainSource() ?? throw new global::System.InvalidOperationException(\"The asset has no source for these bytes.\"); using var values = copy.CopyValues();");
        code.Append("var memory = await source.CopyChunkAsync(values.").Append(name).AppendLine("Chunk, cancellationToken).ConfigureAwait(false);");
        code.Append("lock (Access) { var fields = WriteFields(); fields.").Append(name).Append(" ??= new(memory, writable: true); return BeginByteEdit(fields.").Append(name).AppendLine(".Write()); } }");
    }

    private static bool IsByteMemory(ITypeSymbol type)
        => type.ToDisplayString() == "System.ReadOnlyMemory<byte>?";

    private static void EmitByteFields(StringBuilder code, IPropertySymbol property)
    {
        string name = property.Name;
        code.Append("public global::System.ReadOnlyMemory<byte>? ").Append(name).Append(" { get => _").Append(name).Append("?.Read; set => Attach").Append(name).AppendLine("Bytes(value.HasValue ? new(value.Value) : null); }");
        code.Append("private global::SomeEngine.Serialization.Containers.SharedBytes? _").Append(name).AppendLine(";");
        code.Append("internal void Attach").Append(name).Append("Bytes(global::SomeEngine.Serialization.Containers.SharedBytes? bytes) { var previous = _").Append(name).Append("; _").Append(name).AppendLine(" = bytes; previous?.Dispose(); }");
        code.Append("internal global::SomeEngine.Serialization.Containers.SharedBytes? Retain").Append(name).Append("Bytes() => _").Append(name).AppendLine("?.Retain();");
    }

    private static readonly SymbolDisplayFormat NullableTypeFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .WithMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers |
            SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier |
            SymbolDisplayMiscellaneousOptions.UseSpecialTypes);

    internal static Compilation AddFieldDeclarations(SourceProductionContext output, Compilation compilation,
        IDictionary<SyntaxTree, Location>? origins = null)
    {
        var roots = Types(compilation.Assembly.GlobalNamespace)
            .Select(type => (Type: type, Attribute: type.GetAttributes().FirstOrDefault(a =>
                a.AttributeClass?.ToDisplayString() == "SomeEngine.Assets.AssetAttribute" && a.ConstructorArguments.Length == 1)))
            .Where(value => value.Attribute is not null).ToArray();
        foreach (var root in roots)
        {
            INamedTypeSymbol type = root.Type;
            if (type.Arity != 0 || type.ContainingType is not null || type.IsRecord || type.IsStatic)
            {
                output.ReportDiagnostic(Diagnostic.Create(InvalidFields, type.Locations.FirstOrDefault(),
                    type.ToDisplayString(), "requires a non-generic top-level partial class"));
                continue;
            }
            string schemaName = root.Attribute!.NamedArguments.FirstOrDefault(p => p.Key == "SchemaName").Value.Value as string
                ?? type.ToDisplayString();
            string fieldsName = type.Name + "Data";
            bool partial = type.GetMembers().OfType<IPropertySymbol>().Any(IsPartial);
            IPropertySymbol[] properties = type.GetMembers().OfType<IPropertySymbol>()
                .Where(p => !p.IsStatic && p.DeclaredAccessibility == Accessibility.Public && p.SetMethod?.DeclaredAccessibility == Accessibility.Public &&
                    (partial ? IsPartial(p) : p.DeclaringSyntaxReferences.Any(r => r.GetSyntax() is PropertyDeclarationSyntax { AccessorList: { } accessors } && accessors.Accessors.All(a => a.Body is null && a.ExpressionBody is null))))
                .ToArray();
            IPropertySymbol[] buffers = properties.Where(p => IsByteMemory(p.Type)).ToArray();
            var code = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
            if (!type.ContainingNamespace.IsGlobalNamespace)
                code.Append("namespace ").Append(type.ContainingNamespace.ToDisplayString()).AppendLine(";");
            code.Append("[global::SomeEngine.Serialization.BinaryContract(global::SomeEngine.Serialization.BinaryCompatibility.ExactSchema, LogicalName = ")
                .Append(Literal(schemaName)).AppendLine(")]");
            code.Append("internal sealed partial class ").Append(fieldsName)
                .Append(buffers.Length == 0 ? "" : " : global::System.IDisposable").AppendLine(" {");
            code.AppendLine("public string? AssetGuid { get; set; }");
            foreach (IPropertySymbol property in properties)
            {
                foreach (AttributeData attribute in property.GetAttributes().Where(a => a.AttributeClass?.ContainingNamespace.ToDisplayString() == "SomeEngine.Serialization"))
                    code.Append('[').Append(attribute.ToString()).AppendLine("]");
                if (IsByteMemory(property.Type)) { EmitByteFields(code, property); continue; }
                code.Append("public ").Append(property.Type.ToDisplayString(NullableTypeFormat)).Append(' ').Append(property.Name).Append(" { get; set; }");
                string initializer = MaterialGen.DefaultExpression(property, compilation);
                if (initializer != "default") code.Append(" = ").Append(initializer).Append(';');
                code.AppendLine();
            }
            code.Append("internal ").Append(fieldsName).Append(" CopyFields() { var copy = (").Append(fieldsName).AppendLine(")MemberwiseClone();");
            foreach (IPropertySymbol buffer in buffers)
                code.Append("copy._").Append(buffer.Name).Append(" = _").Append(buffer.Name).AppendLine("?.Retain();");
            code.AppendLine("return copy; }");
            if (buffers.Length != 0)
            {
                code.AppendLine("public void Dispose() {");
                foreach (IPropertySymbol buffer in buffers) code.Append('_').Append(buffer.Name).AppendLine("?.Dispose();");
                code.AppendLine("}");
            }
            code.AppendLine("}");
            code.Append(type.DeclaredAccessibility == Accessibility.Public ? "public " : "internal ")
                .Append("partial class ").Append(type.Name).AppendLine(" {");
            if (partial)
            {
                code.Append("private ").Append(fieldsName).AppendLine(" _content = new();");
                foreach (IPropertySymbol property in properties)
                    code.Append("public partial ").Append(property.Type.ToDisplayString(NullableTypeFormat)).Append(' ').Append(property.Name)
                        .Append(" { get => _content.").Append(property.Name).Append("; set => _content.").Append(property.Name).AppendLine(" = value; }");
            }
            else
            {
                code.Append("internal static ").Append(type.Name).Append(" CreateValueGenerated(").Append(fieldsName).AppendLine(" fields) => new() {");
                foreach (IPropertySymbol property in properties)
                    code.Append(property.Name).Append(" = fields.").Append(property.Name).AppendLine(",");
                code.AppendLine("};");
            }
            code.AppendLine("}");
            string text = code.ToString();
            output.AddSource(type.Name + ".AssetFields.g.cs", text);
            SyntaxTree tree = CSharpSyntaxTree.ParseText(text,
                (CSharpParseOptions?)compilation.SyntaxTrees.FirstOrDefault()?.Options);
            if (origins is not null) origins.Add(tree, type.Locations.FirstOrDefault() ?? Location.None);
            compilation = compilation.AddSyntaxTrees(tree);
        }
        foreach (var root in roots)
        {
            string ns = root.Type.ContainingNamespace.IsGlobalNamespace ? "" : root.Type.ContainingNamespace.ToDisplayString() + ".";
            INamedTypeSymbol? fields = compilation.GetTypeByMetadataName(ns + root.Type.Name + "Data");
            INamedTypeSymbol? type = compilation.GetTypeByMetadataName(ns + root.Type.Name);
            if (fields is not null && type is not null && root.Attribute!.ConstructorArguments[0].Value is string suffix)
                Emit(output, fields, type, suffix, true);
        }
        return compilation;
    }

    private static bool IsPartial(IPropertySymbol property) => property.DeclaringSyntaxReferences.Any(r =>
        r.GetSyntax() is PropertyDeclarationSyntax syntax && syntax.Modifiers.Any(SyntaxKind.PartialKeyword));

    internal static IEnumerable<INamedTypeSymbol> Types(INamespaceSymbol ns)
    {
        foreach (INamespaceSymbol child in ns.GetNamespaceMembers())
            foreach (INamedTypeSymbol type in Types(child)) yield return type;
        foreach (INamedTypeSymbol type in ns.GetTypeMembers())
        {
            yield return type;
            foreach (INamedTypeSymbol nested in NestedTypes(type)) yield return nested;
        }
    }

    private static IEnumerable<INamedTypeSymbol> NestedTypes(INamedTypeSymbol type)
    {
        foreach (INamedTypeSymbol nested in type.GetTypeMembers())
        {
            yield return nested;
            foreach (INamedTypeSymbol child in NestedTypes(nested)) yield return child;
        }
    }

    private static string Literal(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
