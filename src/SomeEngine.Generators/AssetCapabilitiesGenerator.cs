using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using System.Security.Cryptography;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace SomeEngine.Generators;

/// <summary>Connects declared asset extensions to Microsoft DI without generating import workflows.</summary>
[Generator]
public sealed class AssetCapabilitiesGenerator : IIncrementalGenerator
{
    private const string ImporterAttribute = "SomeEngine.Assets.AssetImporterAttribute";
    private const string BlockAttribute = "SomeEngine.Assets.AssetBlockAttribute";
    private const string CapabilitiesAttribute = "SomeEngine.Assets.AssetCapabilitiesAttribute";
    private const string ImporterInterface = "SomeEngine.Assets.Importing.IAssetImporter<TSource, TSettings>";
    private static readonly DiagnosticDescriptor InvalidDeclaration = new("SEAC001", "Unavailable asset capability",
        "Asset capability '{0}': {1}", "SomeEngine.Assets", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor DuplicateIdentity = new("SEAC002", "Duplicate asset capability identity",
        "Asset capabilities '{0}' and '{1}' declare the same persistent identity '{2}'", "SomeEngine.Assets", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor InvalidRegistration = new("SEAC003", "Invalid asset capability registration",
        "Asset capability registration '{0}': {1}", "SomeEngine.Assets", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor ImporterConstructorParameters = new("SEAC004", "Importer requires parameterless construction",
        "Importer '{0}' requires parameterless constructors; read settings through ImportContext and keep algorithms in the importer", "SomeEngine.Assets", DiagnosticSeverity.Error, true);
    private static readonly SymbolDisplayFormat BlockNameFormat = new(
        globalNamespaceStyle: SymbolDisplayGlobalNamespaceStyle.Omitted,
        typeQualificationStyle: SymbolDisplayTypeQualificationStyle.NameAndContainingTypesAndNamespaces,
        genericsOptions: SymbolDisplayGenericsOptions.IncludeTypeParameters,
        miscellaneousOptions: SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers
            | SymbolDisplayMiscellaneousOptions.UseSpecialTypes);

    public void Initialize(IncrementalGeneratorInitializationContext context) =>
        context.RegisterSourceOutput(context.CompilationProvider, static (output, compilation) => Generate(output, compilation));

    private static void Generate(SourceProductionContext output, Compilation compilation)
    {
        string buildVersion = ComputeBuildVersion(compilation);
        output.AddSource("AssetSourceBuild.g.cs", "// <auto-generated/>\n[assembly: global::System.Reflection.AssemblyMetadata(\"SomeEngine.SourceBuild\", " + Literal(buildVersion) + ")]\n");
        if (compilation.GetTypeByMetadataName(ImporterAttribute) is null) return;
        INamedTypeSymbol[] local = Types(compilation.Assembly.GlobalNamespace).ToArray();
        var importers = new List<Importer>();
        bool valid = true;
        foreach (INamedTypeSymbol type in local.Where(type => Attribute(type, ImporterAttribute) is not null))
        {
            Importer? importer = ReadImporter(output, type, true, buildVersion);
            if (importer is null) { valid = false; continue; }
            importers.Add(importer);
        }

        INamedTypeSymbol[] registrations = local.Where(type => Attribute(type, CapabilitiesAttribute) is not null).ToArray();
        var blocks = new List<INamedTypeSymbol>(local.Where(IsBlock));
        IAssemblySymbol declarationAssembly = compilation.GetTypeByMetadataName(ImporterAttribute)!.ContainingAssembly;
        foreach (IAssemblySymbol assembly in compilation.SourceModule.ReferencedAssemblySymbols)
        {
            // Only assemblies that can carry the declarations need examination. In particular, do not walk the BCL.
            if (!SymbolEqualityComparer.Default.Equals(assembly, declarationAssembly)
                && !assembly.Modules.Any(part => part.ReferencedAssemblySymbols.Any(reference =>
                    SymbolEqualityComparer.Default.Equals(reference, declarationAssembly)))) continue;
            foreach (INamedTypeSymbol type in Types(assembly.GlobalNamespace).Where(IsPublic))
            {
                if (IsBlock(type)) blocks.Add(type);
                if (Attribute(type, ImporterAttribute) is null) continue;
                Importer? importer = ReadImporter(output, type, false, null);
                if (importer is null) valid = false;
                else importers.Add(importer);
            }
        }

        // An extension may legitimately offer two producers for the same block. Only capability identities are unique here.
        var importerIds = new Dictionary<Guid, Importer>();
        foreach (Importer importer in importers)
        {
            if (importerIds.TryGetValue(importer.Id, out Importer previous))
            {
                Duplicate(output, previous.Type, importer.Type, importer.Id.ToString());
                valid = false;
            }
            else importerIds.Add(importer.Id, importer);
        }
        var blockIds = new Dictionary<string, INamedTypeSymbol>(StringComparer.Ordinal);
        foreach (INamedTypeSymbol block in blocks)
        {
            string id = BlockId(block);
            if (blockIds.TryGetValue(id, out INamedTypeSymbol previous))
            {
                Duplicate(output, previous, block, id);
                valid = false;
            }
            else blockIds.Add(id, block);
        }

        INamedTypeSymbol[] indexedBlocks = blocks.Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default)
            .OrderBy(BlockId, StringComparer.Ordinal).ToArray();

        foreach (INamedTypeSymbol registration in registrations)
        {
            if (!IsPublic(registration) || registration.ContainingType is not null || registration.Arity != 0
                || !registration.IsStatic || !IsPartial(registration))
            {
                output.ReportDiagnostic(Diagnostic.Create(InvalidRegistration, Location(registration), registration.Name,
                    "use a public top-level static partial class"));
                continue;
            }
            if (!valid) continue;
            output.AddSource(Hint(registration) + ".Capabilities.g.cs", EmitRegistration(registration,
                indexedBlocks,
                importers.OrderBy(importer => importer.Id).ToArray(), buildVersion));
        }
    }

    private static Importer? ReadImporter(SourceProductionContext output, INamedTypeSymbol type, bool local, string? buildVersion)
    {
        void Error(string reason) => output.ReportDiagnostic(Diagnostic.Create(InvalidDeclaration, Location(type), type.ToDisplayString(), reason));
        if (!IsPublic(type) || type.ContainingType is not null || type.Arity != 0 || type.IsAbstract
            || type.IsStatic || type.TypeKind != TypeKind.Class || type.IsRecord)
        {
            Error("use a public top-level non-generic class implementing IAssetImporter<TSource, TSettings>");
            return null;
        }
        AttributeData attribute = Attribute(type, ImporterAttribute)!;
        if (attribute.ConstructorArguments.Length != 2
            || !Guid.TryParse(attribute.ConstructorArguments[0].Value as string, out Guid id) || id == Guid.Empty)
        { Error("the importer identity must be a non-empty GUID"); return null; }

        INamedTypeSymbol[] interfaces = type.AllInterfaces.Where(candidate =>
            candidate.OriginalDefinition.ToDisplayString() == ImporterInterface).ToArray();
        if (interfaces.Length != 1)
        { Error("implement exactly one IAssetImporter<TSource, TSettings> interface"); return null; }

        var blocks = new List<INamedTypeSymbol>();
        if (attribute.ConstructorArguments[1].IsNull || attribute.ConstructorArguments[1].Kind != TypedConstantKind.Array)
        { Error("declare the produced block types"); return null; }
        foreach (TypedConstant argument in attribute.ConstructorArguments[1].Values)
        {
            if (argument.Value is not INamedTypeSymbol block || !IsPublic(block)
                || !IsBlock(block) || block.Arity != 0)
            { Error("each produced data type must be an accessible non-generic AssetBlock implementing IAssetBlock<T>"); return null; }
            if (blocks.Any(previous => SymbolEqualityComparer.Default.Equals(previous, block)))
            { Error("declare each produced block once"); return null; }
            blocks.Add(block);
        }
        if (blocks.Count == 0)
        { Error("declare at least one produced block"); return null; }

        IMethodSymbol[] parameterizedConstructors = type.InstanceConstructors.Where(constructor => constructor.Parameters.Length != 0).ToArray();
        if (parameterizedConstructors.Length != 0)
        {
            foreach (IMethodSymbol constructor in parameterizedConstructors)
                output.ReportDiagnostic(Diagnostic.Create(ImporterConstructorParameters,
                    constructor.Locations.FirstOrDefault(location => location.IsInSource) ?? Location(type), type.ToDisplayString()));
            return null;
        }
        if (!type.InstanceConstructors.Any(constructor => constructor.DeclaredAccessibility == Accessibility.Public))
        { Error("provide a public parameterless constructor"); return null; }
        INamedTypeSymbol? provider = attribute.NamedArguments.FirstOrDefault(argument => argument.Key == "SettingsProvider").Value.Value as INamedTypeSymbol;
        if (provider is not null && (!IsPublic(provider) || provider.IsAbstract || provider.Arity != 0
            || !provider.InstanceConstructors.Any(value => value.DeclaredAccessibility == Accessibility.Public && value.Parameters.Length == 0)
            || !provider.AllInterfaces.Any(value => value.OriginalDefinition.ToDisplayString() == "SomeEngine.Assets.Importing.IAssetImporterSettings<TSettings>"
                && SymbolEqualityComparer.Default.Equals(value.TypeArguments[0], interfaces[0].TypeArguments[1]))))
        { Error("SettingsProvider must publicly implement IAssetImporterSettings<TSettings> and have a public parameterless constructor"); return null; }
        string version = buildVersion ?? AssemblyBuildVersion(type.ContainingAssembly);
        if (local)
        {
            var versions = new SortedSet<string>(StringComparer.Ordinal) { version };
            var dependencies = new List<INamedTypeSymbol>(blocks);
            TypedConstant declaredInputs = attribute.NamedArguments.FirstOrDefault(argument => argument.Key == "VersionInputs").Value;
            if (declaredInputs.Kind == TypedConstantKind.Array && !declaredInputs.IsNull)
                dependencies.AddRange(declaredInputs.Values.Select(value => value.Value).OfType<INamedTypeSymbol>());
            foreach (INamedTypeSymbol dependency in dependencies)
                if (!SymbolEqualityComparer.Default.Equals(dependency.ContainingAssembly, type.ContainingAssembly))
                {
                    versions.Add(dependency.ContainingAssembly.Identity.ToString());
                    foreach (AttributeData input in dependency.ContainingAssembly.GetAttributes())
                        if (input.AttributeClass?.ToDisplayString() == "System.Reflection.AssemblyMetadataAttribute"
                            && input.ConstructorArguments.Length == 2 && input.ConstructorArguments[0].Value as string == "SomeEngine.SourceBuild")
                            versions.Add(input.ConstructorArguments[1].Value as string ?? "");
                }
            using SHA256 versionHash = SHA256.Create();
            version = BitConverter.ToString(versionHash.ComputeHash(Encoding.UTF8.GetBytes(string.Join("\n", versions)))).Replace("-", "");
        }
        return new Importer(type, id, interfaces[0], blocks.ToArray(), provider, version);
    }

    private static string EmitRegistration(INamedTypeSymbol registration, INamedTypeSymbol[] blocks, Importer[] importers, string buildVersion)
    {
        var code = Begin(registration);
        code.Append("public static partial class @").Append(registration.Name).AppendLine(" {");
        code.Append("public const string BuildVersion = ").Append(Literal(buildVersion)).AppendLine(";");
        EmitBlockIdentity(code);
        EmitSelections(code, blocks, importers);
        code.AppendLine("private sealed class AssetServicesAdded { }");
        code.AppendLine("public static global::System.Collections.Generic.IReadOnlyList<global::SomeEngine.Assets.AssetBlockCapability> BlockCapabilities { get; } = global::System.Array.AsReadOnly(new global::SomeEngine.Assets.AssetBlockCapability[] {");
        foreach (INamedTypeSymbol block in blocks)
            code.Append("new(GetAssetBlockIdentity<").Append(Type(block)).Append(">(), typeof(").Append(Type(block)).AppendLine(")),");
        code.AppendLine("});");
        code.AppendLine("public static global::System.Collections.Generic.IReadOnlyList<global::SomeEngine.Assets.AssetImporterCapability> ImporterCapabilities { get; } = global::System.Array.AsReadOnly(new global::SomeEngine.Assets.AssetImporterCapability[] {");
        foreach (Importer importer in importers)
        {
            code.Append("new(new global::System.Guid(").Append(Literal(importer.Id.ToString())).Append("), typeof(").Append(Type(importer.Type))
                .Append("), typeof(").Append(Type(importer.Service.TypeArguments[0])).Append("), typeof(").Append(Type(importer.Service.TypeArguments[1]))
                .Append("), global::System.Array.AsReadOnly(new global::SomeEngine.Assets.AssetBlockCapability[] {");
            foreach (INamedTypeSymbol block in importer.Blocks)
                code.Append("new(GetAssetBlockIdentity<").Append(Type(block)).Append(">(), typeof(").Append(Type(block)).Append(")),");
            code.Append("}), ").Append(Literal(importer.ImplementationVersion));
            if (importer.SettingsProvider is { } provider)
            {
                code.Append(", static (services, settings) => global::SomeEngine.Assets.Importing.AssetImporter.Bind<")
                    .Append(Type(importer.Service.TypeArguments[0])).Append(", ").Append(Type(importer.Service.TypeArguments[1]))
                    .Append(">(new global::System.Guid(").Append(Literal(importer.Id.ToString()))
                    .Append("), global::System.Array.AsReadOnly(new global::System.Guid[] {");
                foreach (INamedTypeSymbol block in importer.Blocks)
                    code.Append("GetAssetBlockIdentity<").Append(Type(block)).Append(">(),");
                code.Append("}), global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<")
                    .Append(Type(importer.Type)).Append(">(services), new ").Append(Type(provider)).Append("(), settings)");
            }
            code.AppendLine("),");
        }
        code.AppendLine("});");
        code.AppendLine("public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddAssetCapabilities(global::Microsoft.Extensions.DependencyInjection.IServiceCollection services) {");
        code.AppendLine("global::System.ArgumentNullException.ThrowIfNull(services);");
        code.AppendLine("foreach (var existing in services) if (existing.ServiceType == typeof(AssetServicesAdded)) return services;");
        code.AppendLine("var blockIdentities = new global::System.Collections.Generic.Dictionary<global::System.Guid, global::SomeEngine.Assets.AssetBlockCapability>();");
        code.AppendLine("foreach (var block in BlockCapabilities) {");
        code.AppendLine("if (block.Id == global::System.Guid.Empty) throw new global::System.InvalidOperationException($\"Block {block.BlockType} has an empty persistent identity.\");");
        code.AppendLine("if (blockIdentities.TryGetValue(block.Id, out var previous)) throw new global::System.InvalidOperationException($\"Block identity {block.Id} is shared by {previous.BlockType} and {block.BlockType}.\");");
        code.AppendLine("blockIdentities.Add(block.Id, block);");
        code.AppendLine("}");
        code.AppendLine("foreach (var existing in services) { if (existing.ImplementationInstance is global::SomeEngine.Assets.AssetBlockCapability registeredBlock && blockIdentities.TryGetValue(registeredBlock.Id, out var declared) && registeredBlock.BlockType != declared.BlockType) throw new global::System.InvalidOperationException($\"Block identity {registeredBlock.Id} is shared by {registeredBlock.BlockType} and {declared.BlockType}.\"); }");
        code.AppendLine("var installedBlocks = new global::System.Collections.Generic.HashSet<global::System.Guid>();");
        code.AppendLine("var installedImporters = new global::System.Collections.Generic.Dictionary<global::System.Guid, global::SomeEngine.Assets.AssetImporterCapability>();");
        code.AppendLine("foreach (var existing in services) { if (existing.ImplementationInstance is global::SomeEngine.Assets.AssetBlockCapability block) installedBlocks.Add(block.Id); if (existing.ImplementationInstance is global::SomeEngine.Assets.AssetImporterCapability importer) installedImporters[importer.Id] = importer; }");
        code.AppendLine("foreach (var importer in ImporterCapabilities) if (installedImporters.TryGetValue(importer.Id, out var previous) && previous.ImporterType != importer.ImporterType) throw new global::System.InvalidOperationException($\"Importer identity {importer.Id} is shared by {previous.ImporterType} and {importer.ImporterType}.\");");
        code.AppendLine("services.Add(global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor.Singleton(new AssetServicesAdded()));");
        foreach (Importer importer in importers)
        {
            code.Append("if (!installedImporters.ContainsKey(new global::System.Guid(").Append(Literal(importer.Id.ToString())).AppendLine("))) {");
            code.Append("global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAdd(services, global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor.Scoped<")
                .Append(Type(importer.Type)).Append(">(static services => new ").Append(Type(importer.Type)).AppendLine("()));");
            code.Append("services.Add(global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor.Scoped<").Append(Type(importer.Service))
                .Append(">(static services => global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<")
                .Append(Type(importer.Type)).AppendLine(">(services)));");
            code.AppendLine("}");
        }
        code.AppendLine("foreach (var block in BlockCapabilities) if (!installedBlocks.Contains(block.Id)) services.Add(global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor.Singleton(block));");
        code.AppendLine("foreach (var importer in ImporterCapabilities) if (!installedImporters.ContainsKey(importer.Id)) services.Add(global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor.Singleton(importer));");
        code.AppendLine("return services;");
        code.AppendLine("}");
        code.AppendLine("}");
        return code.ToString();
    }

    private static string ChoiceName(INamedTypeSymbol type, IEnumerable<INamedTypeSymbol> types)
        => types.Count(value => value.Name == type.Name) == 1 ? type.Name
            : type.Name + "_" + string.Concat(type.ToDisplayString().Select(value => char.IsLetterOrDigit(value) ? value : '_'));

    private static void EmitSelections(StringBuilder code, INamedTypeSymbol[] blocks, Importer[] importers)
    {
        INamedTypeSymbol[] importerTypes = importers.Select(value => value.Type).ToArray();
        code.AppendLine("public enum BlockKind {");
        for (int index = 0; index < blocks.Length; index++)
            code.Append('@').Append(ChoiceName(blocks[index], blocks)).Append(" = ").Append(index).AppendLine(",");
        code.AppendLine("}");
        code.AppendLine("public enum ImporterKind {");
        for (int index = 0; index < importers.Length; index++)
            code.Append('@').Append(ChoiceName(importers[index].Type, importerTypes)).Append(" = ").Append(index).AppendLine(",");
        code.AppendLine("}");
        code.AppendLine("public static global::System.Collections.Generic.IReadOnlyList<global::SomeEngine.Assets.AssetChoice<BlockKind>> BlockChoices { get; } = global::System.Array.AsReadOnly(new global::SomeEngine.Assets.AssetChoice<BlockKind>[] {");
        foreach (INamedTypeSymbol block in blocks)
            code.Append("new(BlockKind.@").Append(ChoiceName(block, blocks)).Append(", ").Append(Literal(block.Name))
                .Append(", new global::System.Guid(").Append(Literal(BlockId(block))).AppendLine(")),");
        code.AppendLine("});");
        code.AppendLine("public static global::System.Collections.Generic.IReadOnlyList<global::SomeEngine.Assets.AssetChoice<ImporterKind>> ImporterChoices { get; } = global::System.Array.AsReadOnly(new global::SomeEngine.Assets.AssetChoice<ImporterKind>[] {");
        foreach (Importer importer in importers)
            code.Append("new(ImporterKind.@").Append(ChoiceName(importer.Type, importerTypes)).Append(", ").Append(Literal(importer.Type.Name))
                .Append(", new global::System.Guid(").Append(Literal(importer.Id.ToString())).AppendLine(")),");
        code.AppendLine("});");
        code.AppendLine("public static global::SomeEngine.Assets.SourceImporterSettings SelectImporter(ImporterKind kind, global::System.Text.Json.JsonElement settings = default) => new(ImporterCapabilities[(int)kind].Id, settings);");
        code.AppendLine("public static bool ContainsBlock(global::SomeEngine.Assets.Asset asset, BlockKind kind) => kind switch {");
        foreach (INamedTypeSymbol block in blocks)
            code.Append("BlockKind.@").Append(ChoiceName(block, blocks)).Append(" => asset.ContainsBlock<").Append(Type(block)).AppendLine(">(),");
        code.AppendLine("_ => throw new global::System.ArgumentOutOfRangeException(nameof(kind)), }; ");
        code.AppendLine("public static async global::System.Threading.Tasks.ValueTask<global::SomeEngine.Assets.AssetBlock> GetBlockAsync(global::SomeEngine.Assets.Asset asset, BlockKind kind, global::System.Threading.CancellationToken cancellationToken = default) => kind switch {");
        foreach (INamedTypeSymbol block in blocks)
            code.Append("BlockKind.@").Append(ChoiceName(block, blocks)).Append(" => await asset.GetBlockAsync<").Append(Type(block)).AppendLine(">(cancellationToken).ConfigureAwait(false),");
        code.AppendLine("_ => throw new global::System.ArgumentOutOfRangeException(nameof(kind)), }; ");
    }

    private static StringBuilder Begin(INamedTypeSymbol type)
    {
        var code = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        if (!type.ContainingNamespace.IsGlobalNamespace)
            code.Append("namespace ").Append(type.ContainingNamespace.ToDisplayString()).AppendLine(";");
        return code;
    }

    private static IEnumerable<INamedTypeSymbol> Types(INamespaceSymbol space)
    {
        foreach (INamespaceOrTypeSymbol member in space.GetMembers())
        {
            if (member is INamespaceSymbol nested)
            {
                foreach (INamedTypeSymbol type in Types(nested)) yield return type;
            }
            else if (member is INamedTypeSymbol type)
            {
                yield return type;
                foreach (INamedTypeSymbol child in NestedTypes(type)) yield return child;
            }
        }
    }

    private static IEnumerable<INamedTypeSymbol> NestedTypes(INamedTypeSymbol type)
    {
        foreach (INamedTypeSymbol nested in type.GetTypeMembers())
        {
            yield return nested;
            foreach (INamedTypeSymbol child in NestedTypes(nested)) yield return child;
        }
    }

    private static bool IsPublic(INamedTypeSymbol type) => type.DeclaredAccessibility == Accessibility.Public
        && (type.ContainingType is null || IsPublic(type.ContainingType));
    private static bool IsPartial(INamedTypeSymbol type) => type.DeclaringSyntaxReferences.Length != 0
        && type.DeclaringSyntaxReferences.All(reference => reference.GetSyntax() is ClassDeclarationSyntax declaration
            && declaration.Modifiers.Any(SyntaxKind.PartialKeyword));
    private static AttributeData? Attribute(ISymbol type, string name) =>
        type.GetAttributes().FirstOrDefault(attribute => attribute.AttributeClass?.ToDisplayString() == name);
    private static bool IsBlock(INamedTypeSymbol type) => type.Arity == 0 && type.ContainingType?.IsGenericType != true
        && Attribute(type, BlockAttribute) is not null;
    private static string? DeclaredBlockName(INamedTypeSymbol type)
    {
        AttributeData? block = Attribute(type, BlockAttribute);
        if (block is null) return null;
        string? declared = block.ConstructorArguments.Length == 0 ? null : block.ConstructorArguments[0].Value as string;
        return declared ?? type.ToDisplayString(BlockNameFormat);
    }
    private static string BlockId(INamedTypeSymbol type)
    {
        string name = DeclaredBlockName(type) ?? throw new InvalidOperationException("Asset block declaration is missing.");
        byte[] hash;
        using (SHA256 sha = SHA256.Create())
            hash = sha.ComputeHash(Encoding.UTF8.GetBytes("SomeEngine.AssetBlock.v1:" + name));
        StringBuilder value = new(36);
        for (int index = 0; index < 16; index++)
        {
            if (index == 4 || index == 6 || index == 8 || index == 10) value.Append('-');
            value.Append(hash[index].ToString("x2", CultureInfo.InvariantCulture));
        }
        return value.ToString();
    }
    private static void EmitBlockIdentity(StringBuilder code) => code.AppendLine("private static global::System.Guid GetAssetBlockIdentity<T>() where T : global::SomeEngine.Assets.AssetBlock, global::SomeEngine.Assets.IAssetBlock<T> => T.BlockTypeId;");

    private static string ComputeBuildVersion(Compilation compilation)
    {
        using SHA256 hash = SHA256.Create();
        void Append(string value)
        {
            byte[] bytes = Encoding.UTF8.GetBytes(value);
            byte[] length = BitConverter.GetBytes(bytes.Length);
            hash.TransformBlock(length, 0, length.Length, null, 0);
            hash.TransformBlock(bytes, 0, bytes.Length, null, 0);
        }
        foreach (SyntaxTree syntax in compilation.SyntaxTrees.OrderBy(tree => tree.FilePath, StringComparer.Ordinal))
        {
            SyntaxNode root = syntax.GetRoot();
            var declarations = root.DescendantNodes().OfType<TypeDeclarationSyntax>().ToArray();
            var registration = declarations.Where(declaration => compilation.GetSemanticModel(syntax).GetDeclaredSymbol(declaration) is INamedTypeSymbol type
                && Attribute(type, CapabilitiesAttribute) is not null).ToArray();
            if (declarations.Length != 0 && registration.Length == declarations.Length) continue;
            root = root.RemoveNodes(registration, SyntaxRemoveOptions.KeepNoTrivia) ?? root;
            Append(root.WithoutTrivia().NormalizeWhitespace().ToFullString());
        }
        hash.TransformFinalBlock(Array.Empty<byte>(), 0, 0);
        return BitConverter.ToString(hash.Hash!).Replace("-", "");
    }

    private static string AssemblyBuildVersion(IAssemblySymbol assembly)
    {
        foreach (AttributeData attribute in assembly.GetAttributes())
            if (attribute.AttributeClass?.ToDisplayString() == "System.Reflection.AssemblyMetadataAttribute"
                && attribute.ConstructorArguments.Length == 2
                && attribute.ConstructorArguments[0].Value as string == "SomeEngine.SourceBuild")
                return attribute.ConstructorArguments[1].Value as string ?? "";
        return assembly.Identity.ToString();
    }
    private static string Type(ITypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
    private static string Literal(string text) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(text, true);
    private static string Hint(INamedTypeSymbol type) => type.ToDisplayString().Replace('.', '_');
    private static Location? Location(INamedTypeSymbol type) => type.Locations.FirstOrDefault(location => location.IsInSource);
    private static void Duplicate(SourceProductionContext output, INamedTypeSymbol first, INamedTypeSymbol second, string identity) =>
        output.ReportDiagnostic(Diagnostic.Create(DuplicateIdentity, Location(second) ?? Location(first), first.ToDisplayString(), second.ToDisplayString(), identity));

    private sealed class Importer
    {
        public Importer(INamedTypeSymbol type, Guid id, INamedTypeSymbol service, INamedTypeSymbol[] blocks, INamedTypeSymbol? settingsProvider, string implementationVersion)
        { Type = type; Id = id; Service = service; Blocks = blocks; SettingsProvider = settingsProvider; ImplementationVersion = implementationVersion; }
        public INamedTypeSymbol Type { get; }
        public Guid Id { get; }
        public INamedTypeSymbol Service { get; }
        public INamedTypeSymbol[] Blocks { get; }
        public INamedTypeSymbol? SettingsProvider { get; }
        public string ImplementationVersion { get; }
    }
}
