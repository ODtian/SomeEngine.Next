using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Operations;

namespace SomeEngine.Generators;

/// <summary>Hashes declared implementation inputs without turning identity-only type arguments into executable dependencies.</summary>
internal sealed class AssetImplementationVersions
{
    private const string MetadataPrefix = "SomeEngine.ImplementationInputs.v1:";
    private const string FallbackMetadataKey = "SomeEngine.ImplementationFallbackReferences.v1";
    private readonly Compilation _compilation;
    private readonly string _buildVersion;
    private readonly bool _canonicalFailed;
    private readonly CancellationToken _cancellationToken;
    private readonly Action<string, string> _reportMissing;
    private readonly HashSet<string> _missing = new(StringComparer.Ordinal);
    private readonly INamedTypeSymbol[] _localTypes;
    private readonly Dictionary<INamedTypeSymbol, SourceType> _sources = new(SymbolEqualityComparer.Default);
    private readonly Dictionary<string, IAssemblySymbol> _assemblies;
    private readonly Dictionary<IAssemblySymbol, Dictionary<string, string>> _metadata = new(SymbolEqualityComparer.Default);
    private readonly Dictionary<string, string> _versions = new(StringComparer.Ordinal);
    private readonly Dictionary<SyntaxTree, SemanticModel> _models = new();
    private TypeInput[]? _fallbackReferences;

    internal AssetImplementationVersions(Compilation compilation, string buildVersion, CancellationToken cancellationToken, Action<string, string> reportMissing)
    {
        _buildVersion = buildVersion;
        _cancellationToken = cancellationToken;
        _reportMissing = reportMissing;
        _compilation = compilation;
        INamedTypeSymbol[] declared = Types(compilation.Assembly.GlobalNamespace).ToArray();
        // Only these canonical generators supply hidden codec/block implementations. Ordinary
        // implementation-only libraries need no second generator run.
        bool needsCodecs = declared.Any(type => type.GetAttributes().Any(attribute =>
            attribute.AttributeClass?.ToDisplayString() == "SomeEngine.Serialization.BinarySerializableAttribute"
            || attribute.AttributeClass?.ToDisplayString() == "SomeEngine.Assets.AssetBlockAttribute"));
        if (needsCodecs)
        {
            var parse = compilation.SyntaxTrees.FirstOrDefault()?.Options as CSharpParseOptions;
            GeneratorDriver driver = CSharpGeneratorDriver.Create(
                new ISourceGenerator[] { new BinaryContractGenerator().AsSourceGenerator(), new AssetBlockGenerator().AsSourceGenerator() },
                parseOptions: parse);
            driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out Compilation analyzed, out var diagnostics, cancellationToken);
            _canonicalFailed = diagnostics.Any(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error)
                || driver.GetRunResult().Results.Any(result => result.Exception is not null);
            _compilation = analyzed;
        }
        _localTypes = Types(_compilation.Assembly.GlobalNamespace).ToArray();
        _assemblies = _compilation.SourceModule.ReferencedAssemblySymbols.Append(_compilation.Assembly)
            .GroupBy(assembly => assembly.Identity.ToString(), StringComparer.Ordinal)
            .ToDictionary(group => group.Key, group => group.Last(), StringComparer.Ordinal);
    }

    internal string EmitMetadata()
    {
        var text = new StringBuilder("// <auto-generated/>\n");
        foreach (INamedTypeSymbol type in _localTypes.OrderBy(TypeName, StringComparer.Ordinal))
        {
            _cancellationToken.ThrowIfCancellationRequested();
            SourceType source = ReadSource(type);
            text.Append("[assembly: global::System.Reflection.AssemblyMetadata(")
                .Append(Literal(MetadataPrefix + TypeName(type))).Append(", ")
                .Append(Literal(source.Encode())).AppendLine(")]");
        }
        // A fallback reference set is shared by every type in this assembly. Do not duplicate
        // potentially hundreds of reference snapshots in each type's metadata value.
        text.Append("[assembly: global::System.Reflection.AssemblyMetadata(")
            .Append(Literal(FallbackMetadataKey)).Append(", ")
            .Append(Literal(string.Join("\n", FallbackReferences(_compilation.Assembly).Select(input => input.Encode())))).AppendLine(")]");
        return text.ToString();
    }

    internal string GetVersion(INamedTypeSymbol type)
    {
        TypeInput input = TypeInput.From(type, type.OriginalDefinition);
        string key = input.Encode();
        if (_versions.TryGetValue(key, out string version)) return version;
        var visited = new HashSet<string>(StringComparer.Ordinal);
        var parts = new SortedSet<string>(StringComparer.Ordinal) { "SomeEngine.ImplementationBuild.v1" };
        Visit(input, visited, parts, new HashSet<string>(StringComparer.Ordinal));
        version = Hash(parts);
        _versions.Add(key, version);
        return version;
    }

    private void Visit(TypeInput input, HashSet<string> visited, SortedSet<string> parts, HashSet<string> active)
    {
        _cancellationToken.ThrowIfCancellationRequested();
        if (!visited.Add(input.Encode())) return;
        if (input.Name.StartsWith("#assembly:", StringComparison.Ordinal))
        {
            if (TryGetAssembly(input.Assembly, out IAssemblySymbol referenced)) AddAssembly(referenced, parts);
            else parts.Add(input.Name.Substring("#assembly:".Length));
            return;
        }
        if (!TryGetAssembly(input.Assembly, out IAssemblySymbol assembly))
        {
            // C# can compile consumers without implementation-only transitive references.
            // Do not silently publish a different/stale version for that incomplete view.
            if (_missing.Add(input.Encode())) _reportMissing(input.Name, input.Assembly);
            parts.Add("unavailable:" + input.Encode());
            return;
        }
        string definition = input.Assembly + ":" + input.Name;
        if (!active.Add(definition))
        {
            AddAssembly(assembly, parts);
            foreach (TypeInput argument in input.Arguments)
                if (!argument.IsParameter) Visit(argument, visited, parts, active);
            return;
        }
        try
        {
        INamedTypeSymbol? type = assembly.GetTypeByMetadataName(input.Name);
        SourceType? source = type is null ? null : IsLocal(type) ? ReadSource(type) : ReadMetadata(type);
        parts.Add("type:" + assembly.Identity + ":" + input.Encode());
        if (source is null)
        {
            AddAssembly(assembly, parts);
            // Unknown generic implementations may execute any of their type arguments.
            foreach (TypeInput argument in input.Arguments)
                if (!argument.IsParameter) Visit(argument, visited, parts, active);
            return;
        }
        parts.Add("source:" + input.Encode() + ":" + source.Hash);
        if (source.Fallback)
        {
            AddAssembly(assembly, parts);
            foreach (TypeInput reference in FallbackReferences(assembly)) Visit(reference, visited, parts, active);
        }
        foreach (TypeInput dependency in source.Inputs)
        {
            TypeInput? bound = dependency.Bind(input.Arguments);
            if (bound is null)
            {
                // An open generic implementation input cannot prove its implementation closure.
                AddAssembly(assembly, parts);
                continue;
            }
            Visit(bound, visited, parts, active);
        }
        }
        finally { active.Remove(definition); }
    }

    private bool TryGetAssembly(string identity, out IAssemblySymbol assembly)
    {
        if (_assemblies.TryGetValue(identity, out assembly)) return true;
        // A rebuilt dependency may be retargeted to a newer assembly version. Never select
        // arbitrarily between extern-aliased versions with the same simple name.
        if (AssemblyIdentity.TryParseDisplayName(identity, out AssemblyIdentity? parsed) && parsed is not null)
        {
            IAssemblySymbol[] matches = _assemblies.Values.Where(candidate => candidate.Identity.Name == parsed.Name).ToArray();
            if (matches.Length == 1) { assembly = matches[0]; return true; }
        }
        assembly = null!;
        return false;
    }

    private void AddAssembly(IAssemblySymbol assembly, SortedSet<string> parts) => parts.Add(AssemblyInput(assembly));

    private string AssemblyInput(IAssemblySymbol assembly) => "assembly:" + assembly.Identity + ":" +
        (SymbolEqualityComparer.Default.Equals(assembly, _compilation.Assembly)
            ? _buildVersion : ReadAssemblyMetadata(assembly, "SomeEngine.SourceBuild") ?? assembly.Identity.ToString());

    private IEnumerable<TypeInput> FallbackReferences(IAssemblySymbol assembly)
    {
        if (SymbolEqualityComparer.Default.Equals(assembly, _compilation.Assembly))
            return _fallbackReferences ??= _compilation.SourceModule.ReferencedAssemblySymbols
                .Select(reference => TypeInput.AssemblyOnly(reference.Identity.ToString(), AssemblyInput(reference)))
                .OrderBy(input => input.Encode(), StringComparer.Ordinal).ToArray();
        string? encoded = ReadAssemblyMetadata(assembly, FallbackMetadataKey);
        if (encoded is not null)
        {
            try { return encoded.Split('\n').Where(line => line.Length != 0).Select(TypeInput.Decode).ToArray(); }
            catch (FormatException) { }
            catch (ArgumentOutOfRangeException) { }
            catch (OverflowException) { }
        }
        // Older or malformed metadata remains conservative over the references still available.
        return assembly.Modules.SelectMany(module => module.ReferencedAssemblySymbols)
            .Select(reference => TypeInput.AssemblyOnly(reference.Identity.ToString(), AssemblyInput(reference))).ToArray();
    }

    private SourceType? ReadMetadata(INamedTypeSymbol type)
    {
        string? encoded = ReadAssemblyMetadata(type.ContainingAssembly, MetadataPrefix + TypeName(type));
        return encoded is null ? null : SourceType.Decode(encoded);
    }

    private SourceType ReadSource(INamedTypeSymbol type)
    {
        type = type.OriginalDefinition;
        if (_sources.TryGetValue(type, out SourceType source)) return source;
        var declarations = new List<string>();
        var bindings = new SortedSet<string>(StringComparer.Ordinal);
        var inputs = new Dictionary<string, TypeInput>(StringComparer.Ordinal);
        bool fallback = _canonicalFailed;

        void Include(ITypeSymbol? referenced)
        {
            if (referenced is null) return;
            if (referenced.TypeKind == TypeKind.Error) { fallback = true; return; }
            if (referenced is IArrayTypeSymbol array) { Include(array.ElementType); return; }
            if (referenced is ITypeParameterSymbol parameter && parameter.TypeParameterKind == TypeParameterKind.Method)
                return; // Concrete generic-method arguments are included at the invoking expression.
            if (referenced is not INamedTypeSymbol && referenced is not ITypeParameterSymbol) return;
            TypeInput input = TypeInput.From(referenced, type);
            inputs[input.Encode()] = input;
        }
        void IncludeSymbol(ISymbol? symbol)
        {
            if (symbol is IAliasSymbol alias) symbol = alias.Target;
            if (symbol is INamedTypeSymbol named)
            {
                // A signature, typeof operand, generic argument or cast names a type, not its body.
                bindings.Add("identity:" + named.ContainingAssembly?.Identity + ":" + named.ToDisplayString());
                if (named.TypeKind == TypeKind.Error) fallback = true;
                return;
            }
            if (symbol is not IMethodSymbol && symbol is not IPropertySymbol
                && symbol is not IFieldSymbol && symbol is not IEventSymbol) return;
            Include(symbol.ContainingType);
            if (symbol is IMethodSymbol method)
            {
                if (method.ReducedFrom is { } reduced) Include(reduced.ContainingType);
                foreach (ITypeSymbol argument in method.TypeArguments) Include(argument);
                // Compiler-provided operators and function-pointer signatures need not have a declaring type.
                // Only named owners can be reflection APIs; do not invent an executable body for an intrinsic.
                string? owner = method.ContainingType?.ToDisplayString();
                if ((owner == "System.Type" && new[] { "GetMethod", "GetMethods", "GetConstructor", "GetConstructors",
                        "GetProperty", "GetProperties", "GetField", "GetFields", "GetMember", "GetMembers",
                        "GetEvent", "GetEvents", "InvokeMember" }.Contains(method.Name))
                    || owner == "System.Activator" || method.Name == "DynamicInvoke"
                    || (method.ContainingNamespace?.ToDisplayString() == "System.Reflection"
                        && new[] { "Invoke", "CreateDelegate", "GetCustomAttribute", "GetCustomAttributes" }.Contains(method.Name))) fallback = true;
            }
        }
        void IncludeResource(SemanticModel model, ExpressionSyntax resource)
        {
            Include(model.GetTypeInfo(resource, _cancellationToken).Type);
            if (model.GetOperation(resource, _cancellationToken) is IConversionOperation converted)
                Include(converted.Operand.Type);
        }
        void IncludeOperation(IOperation operation)
        {
            if (operation.Type?.TypeKind == TypeKind.Dynamic) fallback = true;
            switch (operation)
            {
                case INameOfOperation: return;
                case ITypeOfOperation: return;
                case ISizeOfOperation size: Include(size.TypeOperand); break;
                case IWithOperation copy: IncludeSymbol(copy.CloneMethod); Include(copy.Operand.Type); break;
                case IImplicitIndexerReferenceOperation indexer:
                    IncludeSymbol(indexer.LengthSymbol); IncludeSymbol(indexer.IndexerSymbol); break;
                case ICollectionExpressionOperation collection: IncludeSymbol(collection.ConstructMethod); break;
                case ISpreadOperation spread:
                    Include(spread.Operand.Type);
                    if (spread.Operand is IConversionOperation spreadConversion) Include(spreadConversion.Operand.Type);
                    break;
                case IInvocationOperation invocation: IncludeSymbol(invocation.TargetMethod); break;
                case IObjectCreationOperation creation: IncludeSymbol(creation.Constructor); break;
                case ITypeParameterObjectCreationOperation creation: Include(creation.Type); break;
                case IDeconstructionAssignmentOperation: fallback = true; break;
                case IMemberReferenceOperation member: IncludeSymbol(member.Member); break;
                case IConversionOperation conversion: IncludeSymbol(conversion.OperatorMethod); break;
                case IBinaryOperation binary: IncludeSymbol(binary.OperatorMethod); break;
                case IUnaryOperation unary: IncludeSymbol(unary.OperatorMethod); break;
                case IIncrementOrDecrementOperation increment: IncludeSymbol(increment.OperatorMethod); break;
                case ICompoundAssignmentOperation assignment: IncludeSymbol(assignment.OperatorMethod); break;
                case IDynamicInvocationOperation: fallback = true; break;
                case IDynamicMemberReferenceOperation: fallback = true; break;
                case IDynamicIndexerAccessOperation: fallback = true; break;
                case IDynamicObjectCreationOperation: fallback = true; break;
                case IFunctionPointerInvocationOperation: fallback = true; break;
            }
            foreach (IOperation child in operation.ChildOperations) IncludeOperation(child);
        }

        // Inline value storage is implementation/encoding, not a phantom reference. In
        // particular Unsafe.SizeOf/MemoryMarshal callers depend on nested struct/enum layout.
        foreach (IFieldSymbol field in type.GetMembers().OfType<IFieldSymbol>())
            if (!field.IsStatic && field.Type.IsValueType) Include(field.Type);
        if (type.BaseType is { SpecialType: SpecialType.None } parent) Include(parent);
        foreach (SyntaxReference reference in type.DeclaringSyntaxReferences)
        {
            SyntaxNode declaration = reference.GetSyntax(_cancellationToken);
            declarations.Add(declaration.WithoutTrivia().NormalizeWhitespace().ToFullString());
            if (!_models.TryGetValue(declaration.SyntaxTree, out SemanticModel model))
            {
                model = _compilation.GetSemanticModel(declaration.SyntaxTree);
                _models.Add(declaration.SyntaxTree, model);
            }
            // Other generators may supply additional members. Never publish a precise closure
            // when those executable bindings are absent from this bounded analysis compilation.
            if (model.GetDiagnostics(declaration.Span, _cancellationToken).Any(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error))
                fallback = true;
            var nameOnlySpans = declaration.DescendantNodes().OfType<InvocationExpressionSyntax>()
                .Where(invocation => invocation.Expression is IdentifierNameSyntax name && name.Identifier.ValueText == "nameof"
                    && model.GetOperation(invocation, _cancellationToken) is INameOfOperation)
                .Select(invocation => invocation.Span).ToArray();
            foreach (SyntaxNode node in declaration.DescendantNodesAndSelf())
            {
                _cancellationToken.ThrowIfCancellationRequested();
                if (nameOnlySpans.Any(span => span.Contains(node.Span)))
                {
                    if (node is ExpressionSyntax || node is PredefinedTypeSyntax)
                    {
                        ISymbol? named = model.GetSymbolInfo(node, _cancellationToken).Symbol;
                        if (named is IAliasSymbol alias) named = alias.Target;
                        IncludeSymbol(named as INamedTypeSymbol ?? named?.ContainingType);
                    }
                    continue;
                }
                if (node is NameSyntax || node is PredefinedTypeSyntax)
                    IncludeSymbol(model.GetSymbolInfo(node, _cancellationToken).Symbol);
                // GetOperation on each expression includes implicit conversions and initializer Add calls.
                // Only immediate symbols are needed here; walking whole method bodies once also covers
                // implicit operations whose syntax is shared with another operation.
                if (node is BaseMethodDeclarationSyntax || node is AccessorDeclarationSyntax
                    || node is ArrowExpressionClauseSyntax || node is EqualsValueClauseSyntax)
                    if (model.GetOperation(node, _cancellationToken) is { } operation) IncludeOperation(operation);
                if (node is ExpressionSyntax expression)
                {
                    IncludeSymbol(model.GetSymbolInfo(expression, _cancellationToken).Symbol);
                    if (model.GetOperation(expression, _cancellationToken) is { } operation)
                    {
                        // Expression roots outside method bodies (for example property initializers).
                        if (operation.Parent is null) IncludeOperation(operation);
                    }
                }
                if (node is MemberAccessExpressionSyntax access
                    && model.GetTypeInfo(access.Expression, _cancellationToken).Type is ITypeParameterSymbol parameter
                    && parameter.TypeParameterKind == TypeParameterKind.Type)
                    Include(parameter); // T.Write/Read is executable dispatch; typeof(T) is not.
                if (node is UsingStatementSyntax use)
                {
                    if (use.Declaration is { } declarationVariables)
                    {
                        Include(model.GetTypeInfo(declarationVariables.Type, _cancellationToken).Type);
                        foreach (VariableDeclaratorSyntax variable in declarationVariables.Variables)
                            if (variable.Initializer is { } initializer) IncludeResource(model, initializer.Value);
                    }
                    if (use.Expression is { } resource) IncludeResource(model, resource);
                }
                if (node is LocalDeclarationStatementSyntax local && !local.UsingKeyword.IsKind(SyntaxKind.None))
                {
                    Include(model.GetTypeInfo(local.Declaration.Type, _cancellationToken).Type);
                    foreach (VariableDeclaratorSyntax variable in local.Declaration.Variables)
                        if (variable.Initializer is { } initializer) IncludeResource(model, initializer.Value);
                }
                if (node is FixedStatementSyntax fixedStatement)
                    foreach (VariableDeclaratorSyntax variable in fixedStatement.Declaration.Variables)
                        if (variable.Initializer is { } initializer)
                            Include(model.GetTypeInfo(initializer.Value, _cancellationToken).Type);
                if (node is ForEachVariableStatementSyntax
                    || node is RecursivePatternSyntax { PositionalPatternClause: not null }) fallback = true;
                if (node is ForEachStatementSyntax each)
                {
                    ForEachStatementInfo info = model.GetForEachStatementInfo(each);
                    IncludeSymbol(info.GetEnumeratorMethod); IncludeSymbol(info.MoveNextMethod);
                    IncludeSymbol(info.CurrentProperty); IncludeSymbol(info.DisposeMethod);
                    IncludeSymbol(info.ElementConversion.MethodSymbol); IncludeSymbol(info.CurrentConversion.MethodSymbol);
                }
                if (node is AwaitExpressionSyntax awaitExpression)
                {
                    AwaitExpressionInfo info = model.GetAwaitExpressionInfo(awaitExpression);
                    IncludeSymbol(info.GetAwaiterMethod); IncludeSymbol(info.GetResultMethod); IncludeSymbol(info.IsCompletedProperty);
                }
            }
        }
        if (inputs.Values.Any(input => !input.IsRepresentable()))
        {
            // Use the same conservative representation locally and after metadata discovery.
            fallback = true;
            inputs.Clear();
        }
        declarations.Sort(StringComparer.Ordinal);
        source = new SourceType(Hash(declarations.Concat(bindings)), inputs.Values.OrderBy(input => input.Encode(), StringComparer.Ordinal).ToArray(), fallback);
        _sources.Add(type, source);
        return source;
    }

    private static IEnumerable<INamedTypeSymbol> Types(INamespaceSymbol space)
    {
        foreach (INamespaceSymbol nested in space.GetNamespaceMembers())
            foreach (INamedTypeSymbol type in Types(nested)) yield return type;
        foreach (INamedTypeSymbol type in space.GetTypeMembers())
            foreach (INamedTypeSymbol nested in Types(type)) yield return nested;
    }

    private static IEnumerable<INamedTypeSymbol> Types(INamedTypeSymbol type)
    {
        yield return type;
        foreach (INamedTypeSymbol nested in type.GetTypeMembers())
            foreach (INamedTypeSymbol child in Types(nested)) yield return child;
    }

    private bool IsLocal(INamedTypeSymbol type) => type.DeclaringSyntaxReferences.Length != 0
        && SymbolEqualityComparer.Default.Equals(type.ContainingAssembly, _compilation.Assembly);

    private static string TypeName(INamedTypeSymbol type)
    {
        type = type.OriginalDefinition;
        if (type.ContainingType is { } containing) return TypeName(containing) + "+" + type.MetadataName;
        string space = type.ContainingNamespace.IsGlobalNamespace ? "" : type.ContainingNamespace.ToDisplayString() + ".";
        return space + type.MetadataName;
    }

    private string? ReadAssemblyMetadata(IAssemblySymbol assembly, string key)
    {
        if (!_metadata.TryGetValue(assembly, out Dictionary<string, string> values))
        {
            values = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (AttributeData attribute in assembly.GetAttributes())
                if (attribute.AttributeClass?.ToDisplayString() == "System.Reflection.AssemblyMetadataAttribute"
                    && attribute.ConstructorArguments.Length == 2
                    && attribute.ConstructorArguments[0].Value is string name
                    && attribute.ConstructorArguments[1].Value is string value) values[name] = value;
            _metadata.Add(assembly, values);
        }
        return values.TryGetValue(key, out string result) ? result : null;
    }

    private static string Literal(string value) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, true);

    private static string Hash(IEnumerable<string> values)
    {
        using SHA256 hash = SHA256.Create();
        foreach (string value in values)
        {
            byte[] bytes = Encoding.UTF8.GetBytes(value);
            byte[] length = BitConverter.GetBytes(bytes.Length);
            hash.TransformBlock(length, 0, length.Length, null, 0);
            hash.TransformBlock(bytes, 0, bytes.Length, null, 0);
        }
        hash.TransformFinalBlock(Array.Empty<byte>(), 0, 0);
        return BitConverter.ToString(hash.Hash!).Replace("-", "");
    }

    private sealed class SourceType
    {
        internal SourceType(string hash, TypeInput[] inputs, bool fallback) { Hash = hash; Inputs = inputs; Fallback = fallback; }
        internal string Hash { get; }
        internal TypeInput[] Inputs { get; }
        internal bool Fallback { get; }
        internal string Encode() => Hash + "\n" + (Fallback ? "1" : "0") + "\n" + string.Join("\n", Inputs.Select(input => input.Encode()));
        internal static SourceType? Decode(string encoded)
        {
            string[] lines = encoded.Split('\n');
            if (lines.Length < 3 || lines[0].Length != 64 || !lines[0].All(Uri.IsHexDigit)
                || (lines[1] != "0" && lines[1] != "1")) return null;
            try { return new SourceType(lines[0], lines.Skip(2).Where(line => line.Length != 0).Select(TypeInput.Decode).ToArray(), lines[1] == "1"); }
            catch (FormatException) { return null; }
            catch (ArgumentOutOfRangeException) { return null; }
            catch (OverflowException) { return null; }
        }
    }

    private sealed class TypeInput
    {
        private TypeInput(string assembly, string name, TypeInput[] arguments, int parameter = -1)
        { Assembly = assembly; Name = name; Arguments = arguments; Parameter = parameter; }
        internal string Assembly { get; }
        internal string Name { get; }
        internal TypeInput[] Arguments { get; }
        internal int Parameter { get; }
        internal bool IsParameter => Parameter >= 0;

        internal static TypeInput AssemblyOnly(string assembly, string snapshot)
            => new(assembly, "#assembly:" + snapshot, Array.Empty<TypeInput>());

        internal static TypeInput From(ITypeSymbol symbol, INamedTypeSymbol context)
        {
            if (symbol is ITypeParameterSymbol parameter)
            {
                ITypeParameterSymbol[] parameters = Parameters(context).ToArray();
                int index = Array.FindIndex(parameters, value => SymbolEqualityComparer.Default.Equals(value, parameter));
                return new TypeInput("", "", Array.Empty<TypeInput>(), index < 0 ? int.MaxValue : index);
            }
            if (symbol is IArrayTypeSymbol array) return From(array.ElementType, context);
            if (symbol is not INamedTypeSymbol type || type.TypeKind == TypeKind.Error || type.ContainingAssembly is null)
                return new TypeInput("", "", Array.Empty<TypeInput>(), int.MaxValue);
            return new TypeInput(type.ContainingAssembly.Identity.ToString(), TypeName(type),
                ArgumentsOf(type).Select(argument => From(argument, context)).ToArray());
        }
        private static IEnumerable<ITypeParameterSymbol> Parameters(INamedTypeSymbol type)
            => (type.ContainingType is { } containing ? Parameters(containing) : Enumerable.Empty<ITypeParameterSymbol>()).Concat(type.TypeParameters);
        private static IEnumerable<ITypeSymbol> ArgumentsOf(INamedTypeSymbol type)
            => (type.ContainingType is { } containing ? ArgumentsOf(containing) : Enumerable.Empty<ITypeSymbol>()).Concat(type.TypeArguments);

        internal TypeInput? Bind(TypeInput[] arguments)
        {
            if (IsParameter) return Parameter < arguments.Length && !arguments[Parameter].IsParameter ? arguments[Parameter] : null;
            var bound = new TypeInput[Arguments.Length];
            for (int index = 0; index < bound.Length; index++)
            {
                // An unused generic slot may remain open; only a dependency on that slot needs fallback.
                bound[index] = Arguments[index].Bind(arguments) ?? Arguments[index];
            }
            return new TypeInput(Assembly, Name, bound);
        }
        internal bool IsRepresentable(int depth = 0) => depth <= 64 && Arguments.All(argument => argument.IsRepresentable(depth + 1));

        internal string Encode()
        {
            if (IsParameter) return "P" + Parameter.ToString(CultureInfo.InvariantCulture) + ":";
            return "N" + Token(Assembly) + Token(Name) + Arguments.Length.ToString(CultureInfo.InvariantCulture) + ":" + string.Concat(Arguments.Select(argument => argument.Encode()));
        }
        private static string Token(string text) => text.Length.ToString(CultureInfo.InvariantCulture) + ":" + text;
        internal static TypeInput Decode(string encoded)
        {
            int offset = 0;
            TypeInput input = Read(encoded, ref offset);
            if (offset != encoded.Length) throw new FormatException();
            return input;
        }
        private static TypeInput Read(string text, ref int offset, int depth = 0)
        {
            if ((uint)offset >= (uint)text.Length || depth > 64) throw new FormatException();
            char kind = text[offset++];
            if (kind == 'P') return new TypeInput("", "", Array.Empty<TypeInput>(), Number(text, ref offset));
            if (kind != 'N') throw new FormatException();
            string assembly = ReadToken(text, ref offset), name = ReadToken(text, ref offset);
            int count = Number(text, ref offset);
            if (count > text.Length - offset) throw new FormatException();
            var arguments = new TypeInput[count];
            for (int index = 0; index < count; index++) arguments[index] = Read(text, ref offset, depth + 1);
            return new TypeInput(assembly, name, arguments);
        }
        private static int Number(string text, ref int offset)
        {
            int end = text.IndexOf(':', offset);
            if (end < offset) throw new FormatException();
            int value = int.Parse(text.Substring(offset, end - offset), NumberStyles.None, CultureInfo.InvariantCulture);
            offset = end + 1;
            return value;
        }
        private static string ReadToken(string text, ref int offset)
        {
            int length = Number(text, ref offset);
            string value = text.Substring(offset, length); offset += length; return value;
        }
    }
}
