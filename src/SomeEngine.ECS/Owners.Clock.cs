namespace SomeEngine.ECS.Owners;

internal sealed class Clock
{
    internal uint Tick = 1;

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    internal uint Acquire()
    {
        return Tick++;
    }

    internal void Write(uint tick)
    {
        Tick = tick;
    }
}


